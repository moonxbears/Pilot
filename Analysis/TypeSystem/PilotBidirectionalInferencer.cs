    #region Bidirectional Synthesis (`Synthesize`) & Top-Down Checking (`Check`) (16.1 & 16.3)

    public PilotType Check(ParserRuleContext expr, PilotType expectedType, PilotSourceSpan expectedOrigin)
    {
        var resolvedExpected = _engine.ResolveType(expectedType);
        if (resolvedExpected.Kind == PilotTypeKind.Any)
        {
            return Synthesize(expr);
        }

        if (expr is PilotParser.TestContext testCtx)
        {
            if (testCtx.lambda_expr() is { } lambda)
            {
                return CheckLambda(lambda, resolvedExpected, expectedOrigin);
            }
            var pipes = testCtx.pipe_expr();
            if (pipes != null && pipes.Length == 1 && testCtx.IF() == null)
            {
                return Check(pipes[0], resolvedExpected, expectedOrigin);
            }
            if (pipes != null && pipes.Length >= 2 && testCtx.IF() != null && testCtx.test() != null)
            {
                Synthesize(pipes[1]);
                var tTrue = Check(pipes[0], resolvedExpected, expectedOrigin);
                var tFalse = Check(testCtx.test(), resolvedExpected, expectedOrigin);
                var joined = JoinTypes(new[] { tTrue, tFalse });
                _nodeTypes[testCtx] = joined;
                return joined;
            }
        }

        if (expr is PilotParser.Pipe_exprContext pipe && pipe.set_query_expr().Length == 1)
            return Check(pipe.set_query_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Set_query_exprContext sq && sq.coalesce_expr().Length == 1 && sq.set_op().Length == 0)
            return Check(sq.coalesce_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Coalesce_exprContext coal && coal.or_test().Length == 1 && coal.catch_clause().Length == 0)
            return Check(coal.or_test()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Or_testContext orT && orT.and_test().Length == 1)
            return Check(orT.and_test()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.And_testContext andT && andT.not_test().Length == 1)
            return Check(andT.not_test()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Not_testContext notT && notT.NOT() == null && notT.comparison() != null)
            return Check(notT.comparison(), resolvedExpected, expectedOrigin);

        if (expr is PilotParser.ComparisonContext comp && comp.range_expr().Length == 1 && comp.comp_op().Length == 0 && comp.pattern().Length == 0)
            return Check(comp.range_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Range_exprContext rng && rng.bitor_expr().Length == 1)
            return Check(rng.bitor_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Bitor_exprContext bor && bor.bitxor_expr().Length == 1)
            return Check(bor.bitxor_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Bitxor_exprContext bxor && bxor.bitand_expr().Length == 1)
            return Check(bxor.bitand_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Bitand_exprContext band && band.shift_expr().Length == 1)
            return Check(band.shift_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Shift_exprContext shf && shf.arith_expr().Length == 1)
            return Check(shf.arith_expr()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Arith_exprContext arith && arith.term().Length == 1)
            return Check(arith.term()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.TermContext term && term.factor().Length == 1)
            return Check(term.factor()[0], resolvedExpected, expectedOrigin);

        if (expr is PilotParser.FactorContext fac && fac.power() != null)
            return Check(fac.power(), resolvedExpected, expectedOrigin);

        if (expr is PilotParser.PowerContext pow && pow.factor() == null && pow.atom_expr() != null)
            return Check(pow.atom_expr(), resolvedExpected, expectedOrigin);

        if (expr is PilotParser.Atom_exprContext atomExpr && (atomExpr.trailer() == null || atomExpr.trailer().Length == 0))
            return CheckAtom(atomExpr.atom(), resolvedExpected, expectedOrigin);

        var actualType = Synthesize(expr);
        var actualOrigin = PilotSourceSpan.FromContext(expr, $"expression '{TruncateSource(expr.GetText())}'");
        VerifyAndUnifyConstraint("TYPE001", resolvedExpected, actualType, expectedOrigin, actualOrigin);
        _nodeTypes[expr] = _engine.ResolveType(actualType);
        return _nodeTypes[expr];
    }

    private PilotType CheckAtom(PilotParser.AtomContext atom, PilotType expectedType, PilotSourceSpan expectedOrigin)
    {
        var resolvedExpected = _engine.ResolveType(expectedType);

        if (atom.collection_expr() is { } colExpr)
        {
            var elements = colExpr.collection_element();
            if (resolvedExpected.Kind == PilotTypeKind.Collection &&
                string.Equals(resolvedExpected.Name, "List", StringComparison.OrdinalIgnoreCase) &&
                resolvedExpected.TypeArguments.Count == 1)
            {
                var elemExpected = resolvedExpected.TypeArguments[0];
                if (elements == null || elements.Length == 0)
                {
                    _nodeTypes[atom] = resolvedExpected;
                    return resolvedExpected;
                }

                var elemOrigin = new PilotSourceSpan(
                    expectedOrigin.StartLine,
                    expectedOrigin.StartColumn,
                    expectedOrigin.EndLine,
                    expectedOrigin.EndColumn,
                    expectedOrigin.SourceText,
                    $"element type of '{resolvedExpected}' from {expectedOrigin.OriginDescription}");
                foreach (var el in elements)
                {
                    if (el.test() != null)
                        Check(el.test(), elemExpected, elemOrigin);
                }
                var finalList = PilotType.ListOf(_engine.ResolveType(elemExpected));
                _nodeTypes[atom] = finalList;
                return finalList;
            }
        }

        if (atom.LBRACE() != null && atom.dictorsetmaker() == null)
        {
            if (resolvedExpected.Kind == PilotTypeKind.Collection &&
                (string.Equals(resolvedExpected.Name, "Map", StringComparison.OrdinalIgnoreCase) ||
                 string.Equals(resolvedExpected.Name, "Set", StringComparison.OrdinalIgnoreCase)))
            {
                _nodeTypes[atom] = resolvedExpected;
                return resolvedExpected;
            }
        }

        if (atom.if_stmt() is { } ifStmt)
            return AnalyzeIfStmt(ifStmt, resolvedExpected, expectedOrigin, null);
        if (atom.match_stmt() is { } matchStmt)
            return AnalyzeMatchStmt(matchStmt, resolvedExpected, expectedOrigin, null);
        if (atom.for_stmt() is { } forStmt)
            return AnalyzeForStmt(forStmt, resolvedExpected, expectedOrigin, null);

        var synthesized = SynthesizeAtom(atom);
        var actualOrigin = PilotSourceSpan.FromContext(atom, $"expression '{TruncateSource(atom.GetText())}'");
        VerifyAndUnifyConstraint("TYPE001", resolvedExpected, synthesized, expectedOrigin, actualOrigin);
        _nodeTypes[atom] = _engine.ResolveType(synthesized);
        return _nodeTypes[atom];
    }

    private PilotType CheckLambda(PilotParser.Lambda_exprContext lambda, PilotType expectedType, PilotSourceSpan expectedOrigin)
    {
        var resolvedExpected = _engine.ResolveType(expectedType);
        var paramList = ExtractLambdaParameters(lambda);

        _engine.PushScope();
        PushFlowScope();

        var inferredParamTypes = new List<PilotType>();
        for (int i = 0; i < paramList.Count; i++)
        {
            var (pName, explicitType, token) = paramList[i];
            PilotType pType;
            if (explicitType != null)
            {
                pType = explicitType;
            }
            else if (resolvedExpected.Kind == PilotTypeKind.Function && i < resolvedExpected.TypeArguments.Count)
            {
                pType = _engine.ResolveType(resolvedExpected.TypeArguments[i]);
            }
            else
            {
                pType = PilotType.NewTypeVariable("P");
            }

            inferredParamTypes.Add(pType);
            _engine.SetVariableType(pName, pType);
            SetFlowNarrowedType(pName, pType, token?.Line ?? lambda.Start.Line);

            if (explicitType == null && token != null && pType.Kind != PilotTypeKind.Any && pType.Kind != PilotTypeKind.TypeVariable)
            {
                AddInlayHint(
                    token.Line - 1,
                    token.Column + (token.Text?.Length ?? pName.Length),
                    $": {pType}",
                    PilotInlayHintKind.Type,
                    tooltip: $"Inferred lambda parameter type for '{pName}'");
            }
        }

        PilotType? expectedReturn = resolvedExpected.Kind == PilotTypeKind.Function ? resolvedExpected.ReturnType : null;
        if (lambda.type_spec() != null)
            expectedReturn = PilotTypeInferenceEngine.ParseTypeString(lambda.type_spec().GetText());

        _expectedReturnStack.Push(expectedReturn);
        PilotType bodyReturnType = PilotType.Void;

        var singleTest = lambda.test() ?? lambda.lambda_body()?.test();
        var bodyStmts = lambda.stmt() is { Length: > 0 } s1 ? s1 : lambda.lambda_body()?.stmt();

        if (singleTest != null)
        {
            if (expectedReturn != null && expectedReturn.Kind != PilotTypeKind.Any && expectedReturn.Kind != PilotTypeKind.TypeVariable)
            {
                var retOrigin = PilotSourceSpan.FromContext(lambda, $"expected lambda return type from {expectedOrigin.OriginDescription}");
                bodyReturnType = Check(singleTest, expectedReturn, retOrigin);
            }
            else
            {
                bodyReturnType = Synthesize(singleTest);
                if (expectedReturn != null)
                    expectedReturn.Unify(bodyReturnType, _engine.Substitutions);
            }
        }
        else if (bodyStmts != null && bodyStmts.Length > 0)
        {
            var collectedReturns = new List<PilotType>();
            PilotType lastStmt = PilotType.Void;
            foreach (var st in bodyStmts)
            {
                lastStmt = AnalyzeStatement(st, collectedReturns);
            }
            bodyReturnType = collectedReturns.Count > 0 ? JoinTypes(collectedReturns) : lastStmt;
            if (expectedReturn != null)
            {
                var retOrigin = PilotSourceSpan.FromContext(lambda, $"expected lambda return type from {expectedOrigin.OriginDescription}");
                var actualOrigin = PilotSourceSpan.FromContext(bodyStmts[^1], "lambda return statement");
                VerifyAndUnifyConstraint("TYPE004", expectedReturn, bodyReturnType, retOrigin, actualOrigin);
            }
        }

        _expectedReturnStack.Pop();
        PopFlowScope();
        _engine.PopScope();

        var resolvedParams = inferredParamTypes.Select(_engine.ResolveType).ToArray();
        var resolvedRet = _engine.ResolveType(bodyReturnType);
        var fnType = PilotType.FunctionOf(resolvedParams, resolvedRet);
        _nodeTypes[lambda] = fnType;
        return fnType;
    }

    private static List<(string Name, PilotType? ExplicitType, IToken? Token)> ExtractLambdaParameters(PilotParser.Lambda_exprContext lambda)
    {
        var list = new List<(string, PilotType?, IToken?)>();
        if (lambda.identifier() is { } singleId)
        {
            list.Add((singleId.GetText(), null, singleId.Start));
            return list;
        }

        var parameters = lambda.parameters()?.parameter() ?? lambda.lambda_params()?.parameters()?.parameter();
        if (parameters != null)
        {
            foreach (var p in parameters)
            {
                string pName = p.identifier()?.GetText() ?? "arg";
                PilotType? exp = p.type_annotation()?.type_spec() is { } ts
                    ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                    : null;
                list.Add((pName, exp, p.identifier()?.Start));
            }
            return list;
        }

        if (lambda.lambda_params()?.lambda_param() is { } lParams)
        {
            foreach (var lp in lParams)
            {
                string pName = lp.identifier().GetText();
                PilotType? exp = lp.type_annotation()?.type_spec() is { } ts
                    ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                    : null;
                list.Add((pName, exp, lp.identifier().Start));
            }
        }
        return list;
    }

    public PilotType Synthesize(ParserRuleContext? expr)
    {
        if (expr == null) return PilotType.Any;

        PilotType result = expr switch
        {
            PilotParser.TestContext t => SynthesizeTest(t),
            PilotParser.Lambda_exprContext l => CheckLambda(l, PilotType.Any, PilotSourceSpan.FromContext(l, "lambda expression")),
            PilotParser.Pipe_exprContext p => SynthesizePipeExpr(p),
            PilotParser.Set_query_exprContext sq => SynthesizeSetQueryExpr(sq),
            PilotParser.Coalesce_exprContext c => SynthesizeCoalesceExpr(c),
            PilotParser.Or_testContext o => SynthesizeOrTest(o),
            PilotParser.And_testContext a => SynthesizeAndTest(a),
            PilotParser.Not_testContext n => SynthesizeNotTest(n),
            PilotParser.ComparisonContext cmp => SynthesizeComparison(cmp),
            PilotParser.Range_exprContext r => SynthesizeRangeExpr(r),
            PilotParser.Bitor_exprContext bo => SynthesizeBitorExpr(bo),
            PilotParser.Bitxor_exprContext bx => SynthesizeBitxorExpr(bx),
            PilotParser.Bitand_exprContext ba => SynthesizeBitandExpr(ba),
            PilotParser.Shift_exprContext sh => SynthesizeShiftExpr(sh),
            PilotParser.Arith_exprContext ar => SynthesizeArithExpr(ar),
            PilotParser.TermContext tm => SynthesizeTerm(tm),
            PilotParser.FactorContext fc => SynthesizeFactor(fc),
            PilotParser.PowerContext pw => SynthesizePower(pw),
            PilotParser.Atom_exprContext ae => SynthesizeAtomExpr(ae),
            PilotParser.AtomContext at => SynthesizeAtom(at),
            _ => PilotType.Any
        };

        result = _engine.ResolveType(result);
        _nodeTypes[expr] = result;
        return result;
    }

    private PilotType SynthesizeTest(PilotParser.TestContext ctx)
    {
        if (ctx.lambda_expr() is { } lambda)
            return CheckLambda(lambda, PilotType.Any, PilotSourceSpan.FromContext(lambda, "lambda expression"));

        var pipes = ctx.pipe_expr();
        if (pipes == null || pipes.Length == 0) return PilotType.Any;

        if (ctx.IF() != null && pipes.Length >= 2 && ctx.test() != null)
        {
            var (trueN, falseN, _) = ExtractConditionNarrowing(pipes[1]);
            PushFlowScope();
            foreach (var kvp in trueN) SetFlowNarrowedType(kvp.Key, kvp.Value, pipes[0].Start?.Line);
            var tTrue = Synthesize(pipes[0]);
            PopFlowScope();

            PushFlowScope();
            foreach (var kvp in falseN) SetFlowNarrowedType(kvp.Key, kvp.Value, ctx.test().Start?.Line);
            var tFalse = Synthesize(ctx.test());
            PopFlowScope();

            return JoinTypes(new[] { tTrue, tFalse });
        }

        return Synthesize(pipes[0]);
    }

    private PilotType SynthesizePipeExpr(PilotParser.Pipe_exprContext ctx)
    {
        var stages = ctx.set_query_expr();
        if (stages == null || stages.Length == 0) return PilotType.Any;
        PilotType current = Synthesize(stages[0]);
        for (int i = 1; i < stages.Length; i++)
        {
            current = SynthesizePipeStage(current, stages[i]);
        }
        return current;
    }

    private PilotType SynthesizePipeStage(PilotType inputType, PilotParser.Set_query_exprContext stageCtx)
    {
        if (FindFirstAtomExpr(stageCtx) is { } atomExpr && atomExpr.atom()?.identifier() is { } fnId)
        {
            string fnName = fnId.GetText();
            var trailers = atomExpr.trailer();
            if (trailers != null && trailers.Length > 0 && trailers[0].LPAR() != null)
            {
                var args = trailers[0].arglist()?.argument();
                if (TryInferCollectionHigherOrderMethod(inputType, fnName, args, trailers[0], out var hoResult))
                    return hoResult;
            }
        }
        return Synthesize(stageCtx);
    }

    private PilotType SynthesizeSetQueryExpr(PilotParser.Set_query_exprContext ctx)
    {
        var coals = ctx.coalesce_expr();
        if (coals != null && coals.Length > 0)
            return Synthesize(coals[0]);
        return PilotType.Any;
    }

    private PilotType SynthesizeCoalesceExpr(PilotParser.Coalesce_exprContext ctx)
    {
        var orTests = ctx.or_test();
        if (orTests == null || orTests.Length == 0) return PilotType.Any;

        PilotType current = Synthesize(orTests[0]);
        var catches = ctx.catch_clause();
        if (catches != null && catches.Length > 0)
        {
            PilotType errType = current.IsResult ? current.TypeArguments[1] : PilotType.Any;
            var catchTypes = new List<PilotType>();
            foreach (var cc in catches)
            {
                _engine.PushScope();
                PushFlowScope();
                if (cc.identifier() != null)
                {
                    string errVar = cc.identifier().GetText();
                    _engine.SetVariableType(errVar, errType);
                    SetFlowNarrowedType(errVar, errType, cc.Start?.Line);
                }
                if (cc.test() != null)
                    catchTypes.Add(Synthesize(cc.test()));
                else if (cc.or_test() != null)
                    catchTypes.Add(Synthesize(cc.or_test()));
                else if (cc.block()?.stmt() is { } bStmts)
                {
                    var rets = new List<PilotType>();
                    foreach (var st in bStmts) AnalyzeStatement(st, rets);
                    if (rets.Count > 0) catchTypes.Add(JoinTypes(rets));
                }
                PopFlowScope();
                _engine.PopScope();
            }
            if (current.IsResult)
                current = current.TypeArguments[0];
        }
        else if (orTests.Length > 1)
        {
            PilotType fallbackType = PilotType.Any;
            for (int i = 1; i < orTests.Length; i++)
                fallbackType = Synthesize(orTests[i]);
            if (current.Kind == PilotTypeKind.Option && current.TypeArguments.Count == 1)
                current = current.TypeArguments[0];
            else if (current.Kind == PilotTypeKind.Null)
                current = fallbackType;
        }
        return current;
    }

    private PilotType SynthesizeOrTest(PilotParser.Or_testContext ctx)
    {
        var ands = ctx.and_test();
        if (ands.Length == 1) return Synthesize(ands[0]);
        ExtractConditionNarrowing(ctx);
        return PilotType.Bool;
    }

    private PilotType SynthesizeAndTest(PilotParser.And_testContext ctx)
    {
        var nots = ctx.not_test();
        if (nots.Length == 1) return Synthesize(nots[0]);
        ExtractConditionNarrowing(ctx);
        return PilotType.Bool;
    }

    private PilotType SynthesizeNotTest(PilotParser.Not_testContext ctx)
    {
        if ((ctx.NOT() != null || ctx.EXCLAMATION() != null || ctx.CALL_QUOTE_DEEP() != null) && ctx.not_test() != null)
        {
            Synthesize(ctx.not_test());
            return PilotType.Bool;
        }
        return ctx.comparison() != null ? SynthesizeComparison(ctx.comparison()) : PilotType.Any;
    }

    private PilotType SynthesizeComparison(PilotParser.ComparisonContext ctx)
    {
        var ranges = ctx.range_expr();
        if (ranges == null || ranges.Length == 0) return PilotType.Any;
        if (ranges.Length == 1 && ctx.comp_op().Length == 0 && ctx.pattern().Length == 0)
            return SynthesizeRangeExpr(ranges[0]);

        var lhs = SynthesizeRangeExpr(ranges[0]);
        for (int i = 1; i < ranges.Length; i++)
        {
            var rhs = SynthesizeRangeExpr(ranges[i]);
            if (ctx.comp_op() is { Length: > 0 } ops && ops[0].GetText() is "<" or "<=" or ">" or ">=")
            {
                ConstrainTypeVariable(lhs, PilotTypeClassConstraint.Comparable);
                ConstrainTypeVariable(rhs, PilotTypeClassConstraint.Comparable);
                lhs.Unify(rhs, _engine.Substitutions);
            }
        }
        return PilotType.Bool;
    }

    private PilotType SynthesizeRangeExpr(PilotParser.Range_exprContext ctx)
    {
        var bitors = ctx.bitor_expr();
        if (bitors == null || bitors.Length == 0) return PilotType.Any;
        if (bitors.Length == 1) return SynthesizeBitorExpr(bitors[0]);
        SynthesizeBitorExpr(bitors[0]);
        SynthesizeBitorExpr(bitors[1]);
        return PilotType.ListOf(PilotType.Int);
    }

    private PilotType SynthesizeBitorExpr(PilotParser.Bitor_exprContext ctx)
    {
        var xs = ctx.bitxor_expr();
        var cur = SynthesizeBitxorExpr(xs[0]);
        for (int i = 1; i < xs.Length; i++) cur = SynthesizeBitxorExpr(xs[i]);
        return cur;
    }

    private PilotType SynthesizeBitxorExpr(PilotParser.Bitxor_exprContext ctx)
    {
        var xs = ctx.bitand_expr();
        var cur = SynthesizeBitandExpr(xs[0]);
        for (int i = 1; i < xs.Length; i++) cur = SynthesizeBitandExpr(xs[i]);
        return cur;
    }

    private PilotType SynthesizeBitandExpr(PilotParser.Bitand_exprContext ctx)
    {
        var xs = ctx.shift_expr();
        var cur = SynthesizeShiftExpr(xs[0]);
        for (int i = 1; i < xs.Length; i++) cur = SynthesizeShiftExpr(xs[i]);
        return cur;
    }

    private PilotType SynthesizeShiftExpr(PilotParser.Shift_exprContext ctx)
    {
        var xs = ctx.arith_expr();
        var cur = SynthesizeArithExpr(xs[0]);
        for (int i = 1; i < xs.Length; i++) cur = SynthesizeArithExpr(xs[i]);
        return cur;
    }

    private PilotType SynthesizeArithExpr(PilotParser.Arith_exprContext ctx)
    {
        var terms = ctx.term();
        if (terms == null || terms.Length == 0) return PilotType.Any;

        PilotType current = SynthesizeTerm(terms[0]);
        for (int i = 1; i < terms.Length; i++)
        {
            PilotType next = SynthesizeTerm(terms[i]);
            current = CombineArithmeticOperandTypes(current, next, PilotTypeClassConstraint.Numeric);
        }
        return current;
    }

    private PilotType SynthesizeTerm(PilotParser.TermContext ctx)
    {
        var factors = ctx.factor();
        if (factors == null || factors.Length == 0) return PilotType.Any;

        PilotType current = SynthesizeFactor(factors[0]);
        for (int i = 1; i < factors.Length; i++)
        {
            PilotType next = SynthesizeFactor(factors[i]);
            current = CombineArithmeticOperandTypes(current, next, PilotTypeClassConstraint.Numeric);
        }
        return current;
    }

    private PilotType CombineArithmeticOperandTypes(
        PilotType left,
        PilotType right,
        PilotTypeClassConstraint constraint)
    {
        left = _engine.ResolveType(left);
        right = _engine.ResolveType(right);

        if (left == PilotType.String || right == PilotType.String)
            return PilotType.String;

        ConstrainTypeVariable(left, constraint);
        ConstrainTypeVariable(right, constraint);

        if (left.Kind == PilotTypeKind.TypeVariable || right.Kind == PilotTypeKind.TypeVariable)
        {
            left.Unify(right, _engine.Substitutions);
            return _engine.ResolveType(left);
        }

        if (left == PilotType.Float || right == PilotType.Float)
            return PilotType.Float;
        if (left == PilotType.Int && right == PilotType.Int)
            return PilotType.Int;

        return left;
    }

    private void ConstrainTypeVariable(PilotType type, PilotTypeClassConstraint constraint)
    {
        var resolved = _engine.ResolveType(type);
        if (resolved.Kind == PilotTypeKind.TypeVariable)
        {
            var constrained = resolved.WithConstraint(constraint);
            _engine.Substitutions[resolved.TypeVarId] = constrained;

            if (_activeSchemeStack.Count > 0 && _activeSchemeStack.Peek() is { } activeScheme)
            {
                foreach (var rowMap in activeScheme.RowParameterFields.Values)
                {
                    foreach (var key in rowMap.Keys.ToList())
                    {
                        if (rowMap[key].TypeVarId == resolved.TypeVarId)
                            rowMap[key] = constrained;
                    }
                }
            }
        }
    }

    private PilotType SynthesizeFactor(PilotParser.FactorContext ctx)
    {
        if (ctx.factor() != null)
        {
            var inner = SynthesizeFactor(ctx.factor());
            if (ctx.MINUS() != null || ctx.PLUS() != null)
                ConstrainTypeVariable(inner, PilotTypeClassConstraint.Numeric);
            return inner;
        }
        if (ctx.unary_op() is { } uop)
        {
            if (uop.SPAWN() != null && uop.factor() != null)
            {
                var inner = SynthesizeFactor(uop.factor());
                return PilotType.FutureOf(inner);
            }
            if (uop.AWAIT() != null && uop.factor() != null)
            {
                var inner = SynthesizeFactor(uop.factor());
                if (inner.Kind == PilotTypeKind.Collection && string.Equals(inner.Name, "Future", StringComparison.OrdinalIgnoreCase) && inner.TypeArguments.Count == 1)
                    return inner.TypeArguments[0];
                return inner;
            }
            return PilotType.Any;
        }
        return ctx.power() != null ? SynthesizePower(ctx.power()) : PilotType.Any;
    }

    private PilotType SynthesizePower(PilotParser.PowerContext ctx)
    {
        var baseType = SynthesizeAtomExpr(ctx.atom_expr());
        if (ctx.factor() != null)
        {
            SynthesizeFactor(ctx.factor());
            ConstrainTypeVariable(baseType, PilotTypeClassConstraint.Numeric);
        }
        return baseType;
    }

    private PilotType SynthesizeAtomExpr(PilotParser.Atom_exprContext ctx)
    {
        var trailers = ctx.trailer();
        if (trailers == null || trailers.Length == 0)
        {
            return SynthesizeAtom(ctx.atom());
        }

        if (ctx.atom()?.identifier() is { } rootId && trailers[0].LPAR() != null)
        {
            string calleeName = rootId.GetText();
            if (string.Equals(calleeName, "fail", StringComparison.Ordinal))
            {
                var failArgs = trailers[0].arglist()?.argument();
                PilotType errT = failArgs != null && failArgs.Length > 0 && failArgs[0].test() is { } fTest
                    ? Synthesize(fTest)
                    : PilotType.Any;
                if (_activeSchemeStack.Count > 0 && _activeSchemeStack.Peek() is { } activeScheme && errT.Kind == PilotTypeKind.Primitive)
                {
                    activeScheme.InferredErrorVariants.Add(errT.Name);
                }
                return PilotType.ResultOf(PilotType.Any, errT);
            }
            if (calleeName == "signal")
            {
                var sigArgs = trailers[0].arglist()?.argument();
                PilotType elemType = (sigArgs != null && sigArgs.Length > 0 && sigArgs[0].test() is { } sTest)
                    ? Synthesize(sTest)
                    : PilotType.Any;
                return new PilotType(PilotTypeKind.Collection, "Signal", new[] { elemType });
            }
            if (calleeName is "shared_buffer" or "slice_buffer")
            {
                var bufArgs = trailers[0].arglist()?.argument();
                PilotType elemType = new PilotType(PilotTypeKind.Primitive, "f64");
                if (bufArgs != null)
                {
                    foreach (var ba in bufArgs)
                    {
                        if (ba.test() is { } bTest)
                        {
                            Synthesize(bTest);
                            string argTxt = bTest.GetText().Trim();
                            if (argTxt.StartsWith(':'))
                            {
                                string symElem = argTxt.TrimStart(':').ToLowerInvariant();
                                if (symElem is "f64" or "float" or "f32" or "i64" or "int" or "i32" or "u8" or "byte")
                                {
                                    elemType = new PilotType(PilotTypeKind.Primitive, symElem);
                                }
                            }
                        }
                    }
                }
                return new PilotType(PilotTypeKind.Collection, "SliceBuffer", new[] { elemType });
            }
        }

        PilotType currentType = SynthesizeAtom(ctx.atom());
        string? rootVarName = ctx.atom()?.identifier()?.GetText();
        int effectiveTrailerLen = PilotParser.GetEffectiveTrailerCount(ctx);

        for (int i = 0; i < effectiveTrailerLen; i++)
        {
            var tr = trailers[i];
            currentType = _engine.ResolveType(currentType);

            if (tr.QUESTION() != null && tr.LPAR() == null && tr.LSQB() == null)
            {
                if (currentType.Kind == PilotTypeKind.Option && currentType.TypeArguments.Count == 1)
                {
                    currentType = currentType.TypeArguments[0];
                }
                else if (currentType.IsResult)
                {
                    var errPart = currentType.TypeArguments[1];
                    if (_activeSchemeStack.Count > 0 && _activeSchemeStack.Peek() is { } activeScheme && errPart.Kind != PilotTypeKind.Any)
                    {
                        if (errPart.Kind == PilotTypeKind.Union)
                        {
                            foreach (var u in errPart.TypeArguments)
                                activeScheme.InferredErrorVariants.Add(u.Name);
                        }
                        else
                        {
                            activeScheme.InferredErrorVariants.Add(errPart.Name);
                        }
                    }
                    currentType = currentType.TypeArguments[0];
                }
                continue;
            }

            if (tr.LESS() != null && tr.unit_expr() != null)
            {
                currentType = PilotType.WithUnit(currentType, tr.unit_expr().GetText());
                continue;
            }

            if (tr.LSQB() != null && tr.subscriptlist() != null)
            {
                foreach (var sub in tr.subscriptlist().subscript())
                {
                    if (sub.test() is { Length: > 0 } sTests)
                        Synthesize(sTests[0]);
                }
                if (currentType.Kind == PilotTypeKind.Collection && currentType.TypeArguments.Count > 0)
                {
                    currentType = currentType.TypeArguments[^1];
                }
                else if (currentType.Kind == PilotTypeKind.Tuple && currentType.TypeArguments.Count > 0)
                {
                    currentType = currentType.TypeArguments[0];
                }
                continue;
            }

            if ((tr.DOT() != null || tr.SAFE_NAV() != null) && tr.identifier() != null)
            {
                bool isSafeNav = tr.SAFE_NAV() != null;
                PilotType receiverCore = isSafeNav && currentType.Kind == PilotTypeKind.Option && currentType.TypeArguments.Count == 1
                    ? currentType.TypeArguments[0]
                    : currentType;

                string memberName = tr.identifier().GetText();
                bool nextIsCall = i + 1 < trailers.Length && trailers[i + 1].LPAR() != null;

                if (nextIsCall)
                {
                    var callTrailer = trailers[i + 1];
                    var callArgs = callTrailer.arglist()?.argument();
                    i++;

                    if (TryInferCollectionHigherOrderMethod(receiverCore, memberName, callArgs, callTrailer, out var hoType))
                    {
                        currentType = isSafeNav ? PilotType.OptionOf(hoType) : hoType;
                        continue;
                    }

                    currentType = ResolveMemberMethodCall(receiverCore, rootVarName, memberName, callArgs, callTrailer);
                    if (isSafeNav)
                        currentType = PilotType.OptionOf(currentType);
                    continue;
                }

                if (rootVarName != null && TryRecordRowPolymorphicFieldAccess(rootVarName, memberName, out var rowFieldType))
                {
                    currentType = rowFieldType;
                    continue;
                }

                currentType = LookupFieldType(receiverCore, memberName);
                if (isSafeNav)
                    currentType = PilotType.OptionOf(currentType);
                continue;
            }

            if (tr.cascade_trailer() is { } cascade)
            {
                currentType = SynthesizeCascadeStep(cascade, tr, currentType, rootVarName);
                continue;
            }

            if (tr.LPAR() != null)
            {
                var callArgs = tr.arglist()?.argument();
                currentType = ResolveDirectCall(rootVarName, currentType, callArgs, tr);
                rootVarName = null;
            }
        }

        return _engine.ResolveType(currentType);
    }

    private PilotType SynthesizeCascadeStep(
        PilotParser.Cascade_trailerContext cascade,
        PilotParser.TrailerContext tr,
        PilotType currentType,
        string? rootVarName)
    {
        bool isSafeCascade = cascade.SAFE_CASCADE() != null;
        PilotType receiverCore = isSafeCascade && currentType.Kind == PilotTypeKind.Option && currentType.TypeArguments.Count == 1
            ? currentType.TypeArguments[0]
            : currentType;

        var target = cascade.cascade_target();
        if (target != null)
        {
            if (target.dotted_name() != null && target.LPAR() != null)
            {
                var segments = target.dotted_name().identifier();
                PilotType stepReceiver = receiverCore;
                for (int s = 0; s < segments.Length - 1; s++)
                {
                    stepReceiver = LookupFieldType(stepReceiver, segments[s].GetText());
                }
                string methodName = segments[^1].GetText();
                var callArgs = target.arglist()?.argument();

                PilotType callRetType;
                if (TryInferCollectionHigherOrderMethod(stepReceiver, methodName, callArgs, tr, out var hoType))
                {
                    callRetType = hoType;
                }
                else
                {
                    callRetType = ResolveMemberMethodCall(stepReceiver, segments.Length == 1 ? rootVarName : null, methodName, callArgs, tr);
                    if (callRetType.Kind == PilotTypeKind.Any)
                    {
                        callRetType = InferBuiltinCascadeMemberReturnType(stepReceiver, methodName);
                    }
                }

                if (target.binding_pattern() is { } capPat)
                {
                    BindCascadePatternInInference(target, capPat, _engine.ResolveType(callRetType));
                }
            }
            else if (target.dotted_name() != null && target.LPAR() == null && target.binding_pattern() is { } propCapPat)
            {
                PilotType propType = receiverCore;
                foreach (var seg in target.dotted_name().identifier())
                {
                    string segName = seg.GetText();
                    var nextType = LookupFieldType(propType, segName);
                    if (nextType.Kind == PilotTypeKind.Any)
                    {
                        nextType = InferBuiltinCascadeMemberReturnType(propType, segName);
                    }
                    propType = nextType;
                }
                BindCascadePatternInInference(target, propCapPat, _engine.ResolveType(propType));
            }
            else if (target.dotted_name() != null && target.LPAR() == null && target.EQUAL() != null && target.test() != null)
            {
                var segments = target.dotted_name().identifier();
                PilotType stepReceiver = receiverCore;
                for (int s = 0; s < segments.Length - 1; s++)
                {
                    stepReceiver = LookupFieldType(stepReceiver, segments[s].GetText());
                }
                string propName = segments[^1].GetText();
                PilotType fieldType = LookupFieldType(stepReceiver, propName);
                if (fieldType.Kind != PilotTypeKind.Any)
                    Check(target.test(), fieldType, PilotSourceSpan.FromContext(target, $"cascade field '{propName}'"));
                else
                    Synthesize(target.test());

                foreach (var hc in PilotParser.ExtractHoistedCascades(target.test()))
                {
                    receiverCore = SynthesizeCascadeStep(hc, tr, receiverCore, rootVarName);
                }
            }
            else if (target.LSQB() != null && target.subscriptlist() != null && target.test() != null)
            {
                foreach (var sub in target.subscriptlist().subscript())
                {
                    if (sub.test() is { Length: > 0 } sTests)
                        Synthesize(sTests[0]);
                }
                Synthesize(target.test());

                foreach (var hc in PilotParser.ExtractHoistedCascades(target.test()))
                {
                    receiverCore = SynthesizeCascadeStep(hc, tr, receiverCore, rootVarName);
                }
            }
        }

        if (!string.IsNullOrEmpty(rootVarName))
        {
            var narrowedSelf = LookupFlowAwareType(rootVarName, tr.Start?.Line);
            if (narrowedSelf.Kind != PilotTypeKind.Any && narrowedSelf.ActiveTypestate != null)
            {
                receiverCore = narrowedSelf;
            }
        }
        return isSafeCascade && currentType.Kind == PilotTypeKind.Option
            ? PilotType.OptionOf(receiverCore)
            : receiverCore;
    }

    private void BindCascadePatternInInference(
        PilotParser.Cascade_targetContext target,
        PilotParser.Binding_patternContext capPat,
        PilotType capturedType)
    {
        if (capPat.identifier() is { } capId)
        {
            string varName = capId.GetText();
            _engine.SetVariableType(varName, capturedType);
            SetFlowNarrowedType(varName, capturedType, capPat.Start?.Line);
            if ((target.LET() != null || target.VAR() != null) &&
                capturedType.Kind != PilotTypeKind.Any &&
                capId.Start != null)
            {
                AddInlayHint(
                    capId.Start.Line - 1,
                    capId.Start.Column + varName.Length,
                    $": {capturedType}",
                    PilotInlayHintKind.Type);
            }
        }
        else
        {
            BindDestructuringPattern(capPat, capturedType);
        }
    }

    private static PilotType InferBuiltinCascadeMemberReturnType(PilotType receiverCore, string memberName)
    {
        return memberName switch
        {
            "len" or "length" or "Length" or "count" or "Count" or "capacity" or "data_ptr" or "header_ptr"
                or "element_size" or "stride" or "byte_length" or "byte_capacity" or "abi_header_size"
                or "managed_list_allocations" or "BitLength" => PilotType.Int,
            "contains" or "Contains" or "contains_key" or "ContainsKey" or "is_shared_memory"
                or "is_zero_copy" or "IsBlank" or "Toggle" => PilotType.Bool,
            "to_string" or "ToString" or "shared_name" or "backing_path" or "Trim" or "ToLower"
                or "ToUpper" or "Replace" or "ToHex" => PilotType.String,
            "append" or "add" or "Add" or "clear" or "Clear" or "reset" => PilotType.Void,
            "open_view" or "slice" or "ensure_shared" => receiverCore,
            "pop" when receiverCore.Kind == PilotTypeKind.Collection && receiverCore.TypeArguments.Count > 0 => receiverCore.TypeArguments[^1],
            _ => PilotType.Any
        };
    }

    private bool TryRecordRowPolymorphicFieldAccess(string varName, string fieldName, out PilotType fieldType)
    {
        fieldType = PilotType.Any;
        if (_activeSchemeStack.Count == 0 || _activeSchemeStack.Peek() is not { } scheme)
            return false;

        int paramIdx = scheme.ParameterNames.IndexOf(varName);
        if (paramIdx < 0 || scheme.ParameterHasExplicitType[paramIdx])
            return false;

        if (!scheme.RowParameterFields.TryGetValue(paramIdx, out var fieldMap))
        {
            fieldMap = new Dictionary<string, PilotType>(StringComparer.Ordinal);
            scheme.RowParameterFields[paramIdx] = fieldMap;
        }

        if (!fieldMap.TryGetValue(fieldName, out var existingFieldVar))
        {
            existingFieldVar = PilotType.NewTypeVariable("T");
            fieldMap[fieldName] = existingFieldVar;
        }

        fieldType = _engine.ResolveType(existingFieldVar);
        return true;
    }

    private bool TryInferCollectionHigherOrderMethod(
        PilotType receiverType,
        string methodName,
        PilotParser.ArgumentContext[]? args,
        PilotParser.TrailerContext callTrailer,
        out PilotType resultType)
    {
        resultType = PilotType.Any;
        var resolvedReceiver = _engine.ResolveType(receiverType);
        if (resolvedReceiver.Kind != PilotTypeKind.Collection || resolvedReceiver.TypeArguments.Count == 0)
            return false;

        var elemType = resolvedReceiver.TypeArguments[0];
        string lower = methodName.ToLowerInvariant();

        switch (lower)
        {
            case "filter" or "where":
            {
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest)
                {
                    var predType = PilotType.FunctionOf(new[] { elemType }, PilotType.Bool);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"predicate parameter of '{methodName}' on '{resolvedReceiver}'");
                    Check(aTest, predType, origin);
                }
                resultType = PilotType.ListOf(elemType);
                return true;
            }

            case "map" or "select":
            {
                var outVar = PilotType.NewTypeVariable("U");
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest)
                {
                    var selectorType = PilotType.FunctionOf(new[] { elemType }, outVar);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"selector parameter of '{methodName}' on '{resolvedReceiver}'");
                    var checkedLambda = Check(aTest, selectorType, origin);
                    if (checkedLambda.Kind == PilotTypeKind.Function && checkedLambda.ReturnType != null)
                        outVar = _engine.ResolveType(checkedLambda.ReturnType);
                }
                resultType = PilotType.ListOf(_engine.ResolveType(outVar));
                return true;
            }

            case "flat_map" or "flatmap" or "select_many" or "selectmany":
            {
                var outVar = PilotType.NewTypeVariable("U");
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest)
                {
                    var selectorType = PilotType.FunctionOf(new[] { elemType }, PilotType.ListOf(outVar));
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"selector parameter of '{methodName}' on '{resolvedReceiver}'");
                    var checkedLambda = Check(aTest, selectorType, origin);
                    if (checkedLambda.Kind == PilotTypeKind.Function &&
                        checkedLambda.ReturnType is { Kind: PilotTypeKind.Collection, TypeArguments.Count: > 0 } retCol)
                    {
                        outVar = _engine.ResolveType(retCol.TypeArguments[0]);
                    }
                }
                resultType = PilotType.ListOf(_engine.ResolveType(outVar));
                return true;
            }

            case "find" or "first_or_none":
            {
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest)
                {
                    var predType = PilotType.FunctionOf(new[] { elemType }, PilotType.Bool);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"predicate parameter of '{methodName}'");
                    Check(aTest, predType, origin);
                }
                resultType = PilotType.OptionOf(elemType);
                return true;
            }

            case "any" or "all":
            {
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest)
                {
                    var predType = PilotType.FunctionOf(new[] { elemType }, PilotType.Bool);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"predicate parameter of '{methodName}'");
                    Check(aTest, predType, origin);
                }
                resultType = PilotType.Bool;
                return true;
            }

            case "reduce" or "fold":
            {
                if (args != null && args.Length == 2 && args[0].test() is { } initTest && args[1].test() is { } fnTest)
                {
                    var accType = Synthesize(initTest);
                    var folderType = PilotType.FunctionOf(new[] { accType, elemType }, accType);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"accumulator function of '{methodName}'");
                    Check(fnTest, folderType, origin);
                    resultType = _engine.ResolveType(accType);
                    return true;
                }
                if (args != null && args.Length == 1 && args[0].test() is { } singleFnTest)
                {
                    var folderType = PilotType.FunctionOf(new[] { elemType, elemType }, elemType);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"reducer function of '{methodName}'");
                    Check(singleFnTest, folderType, origin);
                    resultType = elemType;
                    return true;
                }
                return false;
            }

            case "sort_by" or "sortby" or "order_by" or "orderby":
            {
                var keyVar = PilotType.NewTypeVariable("K", PilotTypeClassConstraint.Comparable);
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest)
                {
                    var keyFn = PilotType.FunctionOf(new[] { elemType }, keyVar);
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"key selector of '{methodName}'");
                    Check(aTest, keyFn, origin);
                }
                resultType = PilotType.ListOf(elemType);
                return true;
            }

            case "append" or "push" or "add":
            {
                if (args != null && args.Length >= 1 && args[0].test() is { } aTest && elemType.Kind != PilotTypeKind.Any)
                {
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"element type of '{resolvedReceiver}'");
                    Check(aTest, elemType, origin);
                }
                resultType = PilotType.Void;
                return true;
            }

            case "len" or "count":
                resultType = PilotType.Int;
                return true;

            case "open_view" or "slice":
            {
                if (args != null)
                {
                    foreach (var a in args)
                    {
                        if (a.test() is { } t) Synthesize(t);
                    }
                }
                resultType = resolvedReceiver;
                return true;
            }
        }

        return false;
    }

    private PilotType ResolveMemberMethodCall(
        PilotType receiverType,
        string? receiverVarName,
        string methodName,
        PilotParser.ArgumentContext[]? args,
        PilotParser.TrailerContext callTrailer)
    {
        if (methodName == "transition_to" && args != null && args.Length > 0)
        {
            string targetState = args[0].GetText().Trim().Trim('"', '\'', ':');
            if (!string.IsNullOrEmpty(receiverVarName) && !string.IsNullOrEmpty(targetState))
            {
                var transitioned = PilotType.WithTypestate(receiverType, targetState);
                SetFlowNarrowedType(receiverVarName, transitioned, callTrailer.Start?.Line);
                return transitioned;
            }
        }

        if (_nominalLayouts.TryGetValue(receiverType.Name, out var layout))
        {
            if (layout.MethodRequiredState.TryGetValue(methodName, out var requiredState))
            {
                string? currentState = receiverType.ActiveTypestate ?? layout.InitialState;
                if (!string.IsNullOrEmpty(currentState) && !string.Equals(currentState, requiredState, StringComparison.Ordinal))
                {
                    if (!_suppressDiagnostics)
                    {
                        _engine.ReportDiagnostic(
                            "TYPE012",
                            $"Typestate error: method '{methodName}' requires '{receiverType.Name}[{requiredState}]', but '{receiverVarName ?? receiverType.Name}' is currently in state '{receiverType.Name}[{currentState}]'.",
                            callTrailer.Start.Line,
                            callTrailer.Start.Column);
                    }
                }

                if (!string.IsNullOrEmpty(currentState) &&
                    layout.StateTransitions.TryGetValue((currentState, methodName), out var nextState) &&
                    !string.IsNullOrEmpty(receiverVarName))
                {
                    SetFlowNarrowedType(receiverVarName, PilotType.WithTypestate(layout.NominalType, nextState), callTrailer.Start?.Line);
                }
            }

            if (layout.MethodOverloads.TryGetValue(methodName, out var overloads) && overloads.Count > 0)
            {
                var chosen = SelectBestFunctionOverload(methodName, overloads, args, callTrailer);
                return chosen.ReturnType ?? PilotType.Any;
            }
        }

        if (args != null)
        {
            foreach (var a in args)
            {
                if (a.test() is { } t)
                    Synthesize(t);
            }
        }
        return PilotType.Any;
    }

    private PilotType ResolveDirectCall(
        string? calleeName,
        PilotType calleeType,
        PilotParser.ArgumentContext[]? args,
        PilotParser.TrailerContext callTrailer)
    {
        int argCount = args?.Length ?? 0;
        var quoteKind = Pilot.Analysis.CallQuoting.PilotCallQuotingEngine.GetCallQuoteKind(callTrailer);

        if (quoteKind != Pilot.Analysis.CallQuoting.CallQuoteKind.DeepSplice && args != null && !_suppressDiagnostics)
        {
            foreach (var a in args)
            {
                if (a.TILDE() != null)
                {
                    _engine.ReportDiagnostic(
                        "QUOTE002",
                        $"Unquote prefix '~' on argument '{a.GetText()}' is only valid inside a deep-splice call quote 'fn!!(...)'.",
                        a.Start.Line,
                        a.Start.Column);
                }
            }
        }

        if ((quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.DeepSplice ||
             quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.SymbolicAdjoint) &&
            !string.IsNullOrEmpty(calleeName) &&
            (_externFunctionNames.Contains(calleeName) || !_functionGroups.ContainsKey(calleeName)) &&
            !_suppressDiagnostics)
        {
            if (_externFunctionNames.Contains(calleeName))
            {
                string opStr = quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.SymbolicAdjoint ? "!@" : "!!";
                string verbStr = quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.SymbolicAdjoint ? "differentiate" : "deep-splice";
                _engine.ReportDiagnostic(
                    "QUOTE001",
                    $"Cannot {verbStr} '{calleeName}{opStr}(...)': target function '{calleeName}' is an external FFI or native intrinsic without a white-box Pilot AST body.",
                    callTrailer.Start.Line,
                    callTrailer.Start.Column);
            }
        }

        if (quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.SymbolicAdjoint &&
            !string.IsNullOrEmpty(calleeName) &&
            _functionGroups.TryGetValue(calleeName, out var adjSchemes) &&
            adjSchemes.Count > 0 &&
            !_suppressDiagnostics)
        {
            var adjScheme = adjSchemes[0];
            if (!Pilot.Analysis.Autodiff.PilotSymbolicDifferentiator.ValidateDifferentiableBody(adjScheme.Context.suite(), out string? nonDiffReason))
            {
                _engine.ReportDiagnostic(
                    "QUOTE004",
                    $"Cannot differentiate '{calleeName}!@(...)': function body contains non-differentiable construct ({nonDiffReason}).",
                    callTrailer.Start.Line,
                    callTrailer.Start.Column);
            }
        }

        if (quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.ReactiveSignal && !_suppressDiagnostics)
        {
            bool hasObservable = Pilot.Runtime.Reactive.PilotSignalGraph.HasStaticObservableInput(
                args,
                ident => _mutableVariableNames.Contains(ident) ||
                         (_engine.TryLookupType(ident, out var idType) &&
                          (string.Equals(idType.Name, "Signal", StringComparison.OrdinalIgnoreCase) ||
                           string.Equals(idType.Name, "ComputedSignal", StringComparison.OrdinalIgnoreCase))));
            if (!hasObservable)
            {
                _engine.ReportDiagnostic(
                    "QUOTE005",
                    $"Reactive signal call quote '{calleeName}!^(...)' requires at least one observable input (Signal[T], object property path 'obj.Prop', or mutable 'var' binding), but all arguments are constant or immutable.",
                    callTrailer.Start.Line,
                    callTrailer.Start.Column);
            }
        }

        if (quoteKind == Pilot.Analysis.CallQuoting.CallQuoteKind.AbiFrame &&
            !string.IsNullOrEmpty(calleeName) &&
            _functionGroups.TryGetValue(calleeName, out var abiSchemes) &&
            abiSchemes.Count > 0 &&
            !_suppressDiagnostics)
        {
            var abiScheme = abiSchemes[0];
            for (int i = 0; i < abiScheme.ParameterNames.Count; i++)
            {
                string pName = abiScheme.ParameterNames[i];
                var pType = _engine.ResolveType(abiScheme.ParameterTypes[i]);
                if (!Pilot.Analysis.CallQuoting.PilotCallQuotingEngine.IsUnmanagedAbiCompatibleType(pType.Name))
                {
                    _engine.ReportDiagnostic(
                        "QUOTE003",
                        $"ABI Call-Frame '{calleeName}!&(...)' requires unmanaged / repr(C) parameter layouts, but parameter '{pName}' has type '{pType}'.",
                        callTrailer.Start.Line,
                        callTrailer.Start.Column);
                }
            }
        }

        PilotType underlyingReturn = PilotType.Any;
        bool prevSuppress = _suppressDiagnostics;
        if (quoteKind is Pilot.Analysis.CallQuoting.CallQuoteKind.DeepSplice or Pilot.Analysis.CallQuoting.CallQuoteKind.ReactiveSignal)
        {
            _suppressDiagnostics = true;
        }

        try
        {
            if (!string.IsNullOrEmpty(calleeName) && _functionGroups.TryGetValue(calleeName, out var schemes) && schemes.Count > 0)
            {
                if (schemes.Count == 1)
                {
                    underlyingReturn = ResolveSingleSchemeCall(schemes[0], args, callTrailer);
                }
                else
                {
                    var candidateTypes = schemes.Select(s => s.BuildFunctionType(_engine.Substitutions)).ToList();
                    var selectedFn = SelectBestFunctionOverload(calleeName, candidateTypes, args, callTrailer);
                    underlyingReturn = selectedFn.ReturnType ?? PilotType.Any;
                }
            }
            else if (calleeType.Kind == PilotTypeKind.Function && calleeType.ReturnType != null)
            {
                for (int i = 0; i < argCount; i++)
                {
                    var argExpr = args![i].test();
                    if (argExpr == null) continue;
                    if (i < calleeType.TypeArguments.Count)
                    {
                        var expectedParam = calleeType.TypeArguments[i];
                        var origin = PilotSourceSpan.FromContext(callTrailer, $"parameter #{i + 1} of '{calleeName ?? "function"}'");
                        Check(argExpr, expectedParam, origin);
                    }
                    else
                    {
                        Synthesize(argExpr);
                    }
                }
                underlyingReturn = _engine.ResolveType(calleeType.ReturnType);
            }
            else if (args != null)
            {
                foreach (var a in args)
                {
                    if (a.test() is { } t)
                        Synthesize(t);
                }
            }
        }
        finally
        {
            _suppressDiagnostics = prevSuppress;
        }

        return quoteKind switch
        {
            Pilot.Analysis.CallQuoting.CallQuoteKind.ShallowQuote =>
                new PilotType(PilotTypeKind.Collection, "CallExpr", new[] { underlyingReturn }),
            Pilot.Analysis.CallQuoting.CallQuoteKind.DeepSplice =>
                new PilotType(PilotTypeKind.Collection, "AstExpr", new[] { underlyingReturn }),
            Pilot.Analysis.CallQuoting.CallQuoteKind.AbiFrame =>
                new PilotType(PilotTypeKind.Primitive, $"CallFrame_{calleeName ?? "Anonymous"}"),
            Pilot.Analysis.CallQuoting.CallQuoteKind.ReactiveSignal =>
                new PilotType(PilotTypeKind.Collection, "Signal", new[] { underlyingReturn }),
            Pilot.Analysis.CallQuoting.CallQuoteKind.SymbolicAdjoint =>
                new PilotType(PilotTypeKind.Collection, "Dual", new[] { underlyingReturn }),
            Pilot.Analysis.CallQuoting.CallQuoteKind.EffectDryRun =>
                new PilotType(PilotTypeKind.Collection, "EffectPlan", new[] { underlyingReturn }),
            _ => underlyingReturn
        };
    }

    private PilotType ResolveSingleSchemeCall(
        PilotFunctionScheme scheme,
        PilotParser.ArgumentContext[]? args,
        PilotParser.TrailerContext callTrailer)
    {
        var fnType = scheme.BuildFunctionType(_engine.Substitutions);
        var localSubs = new Dictionary<int, PilotType>();
        var concreteArgTypes = new List<PilotType>();
        var monomorphizedOffsets = new Dictionary<string, int>(StringComparer.Ordinal);
        bool hasRowPolymorphism = scheme.RowParameterFields.Count > 0;

        int argCount = args?.Length ?? 0;
        for (int i = 0; i < argCount; i++)
        {
            var argExpr = args![i].test();
            if (argExpr == null) continue;

            if (i < fnType.TypeArguments.Count)
            {
                var paramType = fnType.TypeArguments[i];

                if (paramType.Kind == PilotTypeKind.RowRecord)
                {
                    var argType = Synthesize(argExpr);
                    concreteArgTypes.Add(argType);
                    VerifyAndBindRowPolymorphicArgument(
                        scheme,
                        i,
                        paramType,
                        argType,
                        argExpr,
                        localSubs,
                        monomorphizedOffsets);
                }
                else
                {
                    var instantiatedParam = PilotType.Resolve(paramType, localSubs);
                    var origin = PilotSourceSpan.FromContext(
                        scheme.Context.parameters()?.parameter()?[i] ?? (ParserRuleContext)scheme.Context,
                        $"parameter '{scheme.ParameterNames[i]}' of function '{scheme.Name}'");
                    var argType = Check(argExpr, instantiatedParam, origin);
                    concreteArgTypes.Add(argType);
                    paramType.Unify(argType, localSubs);
                }
            }
            else
            {
                concreteArgTypes.Add(Synthesize(argExpr));
            }
        }

        var specializedRet = PilotType.Resolve(fnType.ReturnType ?? PilotType.Void, localSubs);
        specializedRet = _engine.ResolveType(specializedRet);

        if (hasRowPolymorphism && concreteArgTypes.Count > 0 && !_suppressDiagnostics)
        {
            var specFnType = PilotType.FunctionOf(concreteArgTypes, specializedRet);
            string suffix = string.Join("_", concreteArgTypes.Select(t => t.Name));
            _monomorphizedCallSites.Add(new PilotMonomorphizedCallSite(
                scheme.Name,
                callTrailer.Start.Line,
                callTrailer.Start.Column,
                concreteArgTypes,
                specializedRet,
                specFnType,
                monomorphizedOffsets,
                $"{scheme.Name}${suffix}"));
        }

        return specializedRet;
    }

    private void VerifyAndBindRowPolymorphicArgument(
        PilotFunctionScheme scheme,
        int paramIndex,
        PilotType rowParamType,
        PilotType argType,
        ParserRuleContext argExpr,
        Dictionary<int, PilotType> localSubs,
        Dictionary<string, int> monomorphizedOffsets)
    {
        foreach (var reqField in rowParamType.RowFields)
        {
            string fieldName = reqField.Key;
            PilotType reqFieldType = reqField.Value;

            if (TryLookupFieldAndOffset(argType, fieldName, out var actualFieldType, out int offset))
            {
                monomorphizedOffsets[fieldName] = offset;
                if (!reqFieldType.Unify(actualFieldType, localSubs))
                {
                    var expectedOrigin = PilotSourceSpan.FromContext(
                        scheme.Context,
                        $"row constraint '{{ {fieldName}: {reqFieldType} }}' on parameter '{scheme.ParameterNames[paramIndex]}' of '{scheme.Name}'");
                    var actualOrigin = PilotSourceSpan.FromContext(argExpr, $"field '{fieldName}: {actualFieldType}' on argument of type '{argType}'");
                    RecordConstraintFailure("TYPE008", reqFieldType, actualFieldType, expectedOrigin, actualOrigin);
                }
            }
            else if (argType.Kind != PilotTypeKind.Any && argType.Kind != PilotTypeKind.TypeVariable)
            {
                var expectedOrigin = PilotSourceSpan.FromContext(
                    scheme.Context,
                    $"structural row parameter '{scheme.ParameterNames[paramIndex]}: {rowParamType}' of '{scheme.Name}'");
                var actualOrigin = PilotSourceSpan.FromContext(argExpr, $"argument of type '{argType}'");
                if (!_suppressDiagnostics)
                {
                    _constraints.Add(new PilotTypeConstraint("TYPE008", rowParamType, argType, expectedOrigin, actualOrigin, isSatisfied: false));
                    _engine.ReportDiagnostic(
                        "TYPE008",
                        $"Structural row mismatch: argument of type '{argType}' is missing required field '{fieldName}' expected by '{scheme.Name}({scheme.ParameterNames[paramIndex]}: {rowParamType})' (defined at line {expectedOrigin.StartLine}).",
                        argExpr.Start.Line,
                        argExpr.Start.Column);
                }
            }
        }
    }

    private PilotType SelectBestFunctionOverload(
        string groupName,
        List<PilotType> candidates,
        PilotParser.ArgumentContext[]? args,
        PilotParser.TrailerContext callTrailer)
    {
        int argCount = args?.Length ?? 0;
        var arityMatches = candidates.Where(c => c.TypeArguments.Count == argCount).ToList();
        if (arityMatches.Count == 0)
            arityMatches = candidates;

        if (arityMatches.Count == 1)
        {
            var single = arityMatches[0];
            for (int i = 0; i < argCount && i < single.TypeArguments.Count; i++)
            {
                var argExpr = args![i].test();
                if (argExpr != null)
                {
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"parameter #{i + 1} of '{groupName}'");
                    Check(argExpr, single.TypeArguments[i], origin);
                }
            }
            return single;
        }

        var argTypes = new PilotType[argCount];
        for (int i = 0; i < argCount; i++)
        {
            var argExpr = args![i].test();
            if (argExpr != null && argExpr.lambda_expr() == null)
                argTypes[i] = Synthesize(argExpr);
            else
                argTypes[i] = PilotType.Any;
        }

        PilotType? bestMatch = null;
        int bestExactScore = -1;

        foreach (var cand in arityMatches)
        {
            if (cand.TypeArguments.Count != argCount) continue;
            bool compatible = true;
            int exactScore = 0;
            for (int i = 0; i < argCount; i++)
            {
                if (argTypes[i] == PilotType.Any) continue;
                if (argTypes[i].Equals(cand.TypeArguments[i]))
                    exactScore += 2;
                else if (argTypes[i].IsAssignableTo(cand.TypeArguments[i]))
                    exactScore += 1;
                else
                {
                    compatible = false;
                    break;
                }
            }

            if (compatible && exactScore > bestExactScore)
            {
                bestExactScore = exactScore;
                bestMatch = cand;
            }
        }

        if (bestMatch != null)
        {
            for (int i = 0; i < argCount; i++)
            {
                var argExpr = args![i].test();
                if (argExpr?.lambda_expr() != null)
                {
                    var origin = PilotSourceSpan.FromContext(callTrailer, $"parameter #{i + 1} of overload '{groupName}{bestMatch}'");
                    Check(argExpr, bestMatch.TypeArguments[i], origin);
                }
            }
            return bestMatch;
        }

        if (!_suppressDiagnostics && argTypes.All(a => a != PilotType.Any))
        {
            string argSig = string.Join(", ", argTypes.Select(a => a.ToString()));
            string candSigs = string.Join("; ", candidates.Select(c => c.ToString()));
            _engine.ReportDiagnostic(
                "TYPE006",
                $"No overload of method group '{groupName}' matches argument types '({argSig})'. Candidates: [{candSigs}].",
                callTrailer.Start.Line,
                callTrailer.Start.Column);
        }

        return arityMatches[0];
    }

    private PilotType SynthesizeAtom(PilotParser.AtomContext ctx)
    {
        if (ctx.literal() is { } lit)
        {
            if (lit.INTEGER() != null || lit.HEX_INTEGER() != null || lit.BIN_INTEGER() != null || lit.OCT_INTEGER() != null)
                return PilotType.Int;
            if (lit.FLOAT_NUMBER() != null)
                return PilotType.Float;
            if (lit.STRING().Length > 0 || lit.TRIPLE_STRING().Length > 0 || lit.FSTRING().Length > 0)
                return PilotType.String;
            if (lit.TRUE() != null || lit.FALSE() != null)
                return PilotType.Bool;
            if (lit.NONE() != null || lit.NULL() != null)
                return PilotType.Null;
        }

        if (ctx.identifier() != null && ctx.DOT() == null)
        {
            string id = ctx.identifier().GetText();
            var resolved = LookupFlowAwareType(id, ctx.Start?.Line);
            _nodeTypes[ctx] = resolved;
            return resolved;
        }

        if (ctx.collection_expr() is { } colExpr)
        {
            var elements = colExpr.collection_element();
            if (elements == null || elements.Length == 0)
            {
                return PilotType.ListOf(PilotType.Any);
            }
            var elemTypes = new List<PilotType>();
            foreach (var el in elements)
            {
                if (el.test() != null)
                    elemTypes.Add(Synthesize(el.test()));
            }
            var joinedElem = elemTypes.Count > 0 ? JoinTypes(elemTypes) : PilotType.Any;
            return PilotType.ListOf(joinedElem);
        }

        if (ctx.LBRACE() != null)
        {
            if (ctx.dictorsetmaker() is { } ds)
            {
                var entries = ds.dict_entry();
                if (entries != null && entries.Length > 0)
                {
                    var rowFields = new Dictionary<string, PilotType>(StringComparer.Ordinal);
                    var keyTypes = new List<PilotType>();
                    var valTypes = new List<PilotType>();
                    bool canBeRow = true;

                    foreach (var entry in entries)
                    {
                        var tests = entry.test();
                        if (tests.Length >= 2)
                        {
                            string rawKey = tests[0].GetText().Trim();
                            var kType = Synthesize(tests[0]);
                            var vType = Synthesize(tests[1]);
                            keyTypes.Add(kType);
                            valTypes.Add(vType);

                            string cleanKey = rawKey.Trim('"', '\'', ':');
                            if (!string.IsNullOrEmpty(cleanKey) && IsSimpleIdentifier(cleanKey))
                                rowFields[cleanKey] = vType;
                            else
                                canBeRow = false;
                        }
                    }

                    string firstKeyRaw = entries[0].test()[0].GetText().Trim();
                    if (canBeRow && !firstKeyRaw.StartsWith('"') && !firstKeyRaw.StartsWith('\''))
                    {
                        return PilotType.RowRecordOf(rowFields, isOpenRow: false);
                    }

                    var kJoined = keyTypes.Count > 0 ? JoinTypes(keyTypes) : PilotType.String;
                    var vJoined = valTypes.Count > 0 ? JoinTypes(valTypes) : PilotType.Any;
                    return PilotType.MapOf(kJoined, vJoined);
                }

                var setElements = ds.collection_element();
                if (setElements != null && setElements.Length > 0)
                {
                    var elemTypes = setElements
                        .Where(e => e.test() != null)
                        .Select(e => Synthesize(e.test()))
                        .ToList();
                    return PilotType.SetOf(elemTypes.Count > 0 ? JoinTypes(elemTypes) : PilotType.Any);
                }
            }
            return PilotType.MapOf(PilotType.String, PilotType.Any);
        }

        if (ctx.LPAR() != null && ctx.testlist_comp() is { } tlc)
        {
            var tests = tlc.test();
            if (tests != null && tests.Length == 1 && tlc.COMMA().Length == 0)
                return Synthesize(tests[0]);
            if (tests != null && tests.Length > 0)
                return PilotType.TupleOf(tests.Select(Synthesize).ToArray());
        }

        if (ctx.symbol_literal() != null)
            return new PilotType(PilotTypeKind.Primitive, "symbol");
        if (ctx.overloadable_op() != null)
            return PilotType.Any;
        if (ctx.if_stmt() is { } ifStmt)
            return AnalyzeIfStmt(ifStmt, null, null, null);
        if (ctx.match_stmt() is { } matchStmt)
            return AnalyzeMatchStmt(matchStmt, null, null, null);
        if (ctx.for_stmt() is { } forStmt)
            return AnalyzeForStmt(forStmt, null, null, null);

        return PilotType.Any;
    }

