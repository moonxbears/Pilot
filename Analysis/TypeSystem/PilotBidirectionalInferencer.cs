    private void VerifyAndUnifyConstraint(
        string code,
        PilotType expectedType,
        PilotType actualType,
        PilotSourceSpan expectedOrigin,
        PilotSourceSpan actualOrigin)
    {
        var exp = _engine.ResolveType(expectedType);
        var act = _engine.ResolveType(actualType);

        if (exp.Kind == PilotTypeKind.Any || act.Kind == PilotTypeKind.Any)
        {
            _constraints.Add(new PilotTypeConstraint(code, exp, act, expectedOrigin, actualOrigin, isSatisfied: true));
            return;
        }

        if (exp.Unify(act, _engine.Substitutions) || act.IsAssignableTo(exp))
        {
            _constraints.Add(new PilotTypeConstraint(code, _engine.ResolveType(exp), _engine.ResolveType(act), expectedOrigin, actualOrigin, isSatisfied: true));
            return;
        }

        RecordConstraintFailure(code, exp, act, expectedOrigin, actualOrigin);
    }

    private void RecordConstraintFailure(
        string code,
        PilotType expectedType,
        PilotType actualType,
        PilotSourceSpan expectedOrigin,
        PilotSourceSpan actualOrigin)
    {
        if (_suppressDiagnostics) return;

        var constraint = new PilotTypeConstraint(code, expectedType, actualType, expectedOrigin, actualOrigin, isSatisfied: false);
        _constraints.Add(constraint);

        _engine.ReportDiagnostic(
            code,
            constraint.FormatDiagnosticMessage(),
            actualOrigin.StartLine,
            actualOrigin.StartColumn);

        if (code == "TYPE001" && expectedOrigin.OriginDescription.StartsWith("type annotation on '", StringComparison.Ordinal))
        {
            string varName = expectedOrigin.OriginDescription["type annotation on '".Length..].TrimEnd('\'');
            _engine.ReportDiagnostic(
                "PILOT300",
                $"Inferred type mismatch on binding '{varName}': cannot assign expression of type '{actualType}' to declared type '{expectedType}'.",
                actualOrigin.StartLine,
                actualOrigin.StartColumn);
        }
    }

    private void AddInlayHint(
        int zeroBasedLine,
        int zeroBasedCharacter,
        string label,
        PilotInlayHintKind kind,
        bool paddingLeft = false,
        bool paddingRight = false,
        string tooltip = "")
    {
        if (zeroBasedLine < 0 || zeroBasedCharacter < 0) return;
        if (_inlayHints.Any(h => h.Line == zeroBasedLine && h.Character == zeroBasedCharacter && h.Label == label))
            return;
        _inlayHints.Add(new PilotInlayHint(zeroBasedLine, zeroBasedCharacter, label, kind, paddingLeft, paddingRight, tooltip));
    }

    private PilotType LookupFieldType(PilotType receiverType, string fieldName)
    {
        if (TryLookupFieldAndOffset(receiverType, fieldName, out var fType, out _))
            return fType;
        return PilotType.Any;
    }

    private bool TryLookupFieldAndOffset(PilotType receiverType, string fieldName, out PilotType fieldType, out int offset)
    {
        fieldType = PilotType.Any;
        offset = -1;
        var resolved = _engine.ResolveType(receiverType);

        if (resolved.Kind == PilotTypeKind.RowRecord)
        {
            int idx = 0;
            foreach (var kvp in resolved.RowFields)
            {
                if (string.Equals(kvp.Key, fieldName, StringComparison.Ordinal))
                {
                    fieldType = kvp.Value;
                    offset = idx;
                    return true;
                }
                idx++;
            }
            return false;
        }

        if (_nominalLayouts.TryGetValue(resolved.Name, out var layout) &&
            layout.FieldMap.TryGetValue(fieldName, out var info))
        {
            fieldType = info.Type;
            offset = info.Offset;
            return true;
        }

        if (_engine.TryLookupType($"{resolved.Name}.{fieldName}", out var qualified))
        {
            fieldType = qualified;
            offset = 0;
            return true;
        }

        if (resolved.Kind == PilotTypeKind.Collection &&
            resolved.TypeArguments.Count > 0 &&
            (string.Equals(resolved.Name, "Signal", StringComparison.OrdinalIgnoreCase) ||
             string.Equals(resolved.Name, "ComputedSignal", StringComparison.OrdinalIgnoreCase) ||
             string.Equals(resolved.Name, "Dual", StringComparison.OrdinalIgnoreCase) ||
             string.Equals(resolved.Name, "EffectPlan", StringComparison.OrdinalIgnoreCase)))
        {
            if (fieldName is "Value" or "value" or "primal")
            {
                fieldType = resolved.TypeArguments[0];
                offset = 0;
                return true;
            }
        }

        if (resolved.Kind == PilotTypeKind.Collection &&
            (string.Equals(resolved.Name, "SliceBuffer", StringComparison.OrdinalIgnoreCase) ||
             string.Equals(resolved.Name, "SharedBuffer", StringComparison.OrdinalIgnoreCase)))
        {
            switch (fieldName)
            {
                case "data_ptr" or "len" or "length" or "capacity" or "element_size" or "byte_length" or "abi_header_size" or "managed_list_allocations":
                    fieldType = PilotType.Int;
                    offset = 0;
                    return true;
                case "is_shared_memory":
                    fieldType = PilotType.Bool;
                    offset = 0;
                    return true;
                case "shared_name":
                    fieldType = PilotType.String;
                    offset = 0;
                    return true;
            }
        }

        return false;
    }

    private PilotType JoinTypes(IReadOnlyList<PilotType> types)
    {
        var resolved = types
            .Select(_engine.ResolveType)
            .Where(t => t != null && t.Kind != PilotTypeKind.Void)
            .ToList();

        if (resolved.Count == 0) return PilotType.Void;
        if (resolved.Count == 1) return resolved[0];

        var concrete = resolved.Where(t => t.Kind != PilotTypeKind.TypeVariable && t.Kind != PilotTypeKind.Any).ToList();
        var typeVars = resolved.Where(t => t.Kind == PilotTypeKind.TypeVariable).ToList();
        if (concrete.Count > 0 && typeVars.Count > 0)
        {
            var joinedConcrete = JoinTypes(concrete);
            foreach (var tv in typeVars)
            {
                tv.Unify(joinedConcrete, _engine.Substitutions);
            }
            return _engine.ResolveType(joinedConcrete);
        }

        bool allEqual = true;
        for (int i = 1; i < resolved.Count; i++)
        {
            if (!resolved[i].Equals(resolved[0]))
            {
                allEqual = false;
                break;
            }
        }
        if (allEqual) return resolved[0];

        if (resolved.All(t => t == PilotType.Int || t == PilotType.Float))
            return resolved.Any(t => t == PilotType.Float) ? PilotType.Float : PilotType.Int;

        return PilotType.UnionOf(resolved.ToArray());
    }

    private PilotType InferSimpleSuiteReturnType(PilotParser.SuiteContext? suite)
    {
        if (suite == null) return PilotType.Void;
        var rets = new List<PilotType>();
        bool prev = _suppressDiagnostics;
        _suppressDiagnostics = true;
        try
        {
            var last = AnalyzeSuiteForReturn(suite, rets);
            if (rets.Count > 0) return JoinTypes(rets);
            return last;
        }
        finally
        {
            _suppressDiagnostics = prev;
        }
    }

    private static bool TryExtractFailArgumentType(
        PilotParser.TestContext testCtx,
        out PilotType errType,
        out string? errTypeName)
    {
        errType = PilotType.Any;
        errTypeName = null;
        string txt = testCtx.GetText().Trim();
        if (!txt.StartsWith("fail(", StringComparison.Ordinal) || !txt.EndsWith(')'))
            return false;

        string inner = txt[5..^1].Trim();
        int parenIdx = inner.IndexOf('(');
        string head = parenIdx > 0 ? inner[..parenIdx].Trim() : inner;
        if (head.Contains('.'))
            head = head[(head.LastIndexOf('.') + 1)..];
        if (IsSimpleIdentifier(head))
        {
            errTypeName = head;
            errType = new PilotType(PilotTypeKind.Primitive, head);
            return true;
        }
        return true;
    }

    private static bool SuiteAlwaysExits(PilotParser.SuiteContext? suite)
    {
        if (suite == null) return false;
        if (suite.simple_stmt() is { } simple)
            return SimpleStmtAlwaysExits(simple);
        if (suite.stmt() is { Length: > 0 } stmts)
        {
            foreach (var st in stmts)
            {
                if (st.simple_stmt() is { } s && SimpleStmtAlwaysExits(s))
                    return true;
                if (st.compound_stmt()?.if_stmt() is { } nestedIf &&
                    nestedIf.ELSE() != null &&
                    nestedIf.suite() is { Length: >= 2 } nSuites &&
                    nSuites.All(SuiteAlwaysExits))
                {
                    return true;
                }
            }
        }
        return false;
    }

    private static bool SimpleStmtAlwaysExits(PilotParser.Simple_stmtContext simple)
    {
        var smalls = simple.small_stmt();
        if (smalls == null) return false;
        foreach (var sm in smalls)
        {
            if (sm.flow_stmt() is { } fl && (fl.RETURN() != null || fl.BREAK() != null || fl.CONTINUE() != null || fl.RAISE() != null))
                return true;
            if (sm.rollback_stmt() != null)
                return true;
            string txt = sm.GetText().Trim();
            if (txt.StartsWith("panic(", StringComparison.Ordinal) || txt.StartsWith("fail(", StringComparison.Ordinal))
                return true;
        }
        return false;
    }

    private static PilotParser.PatternContext? FindIfBranchPattern(PilotParser.If_stmtContext ctx, int branchIndex)
    {
        int currentBranch = -1;
        for (int i = 0; i < ctx.ChildCount; i++)
        {
            var ch = ctx.GetChild(i);
            if (ch is ITerminalNode term && (term.Symbol.Type == PilotLexer.IF || term.Symbol.Type == PilotLexer.ELIF))
                currentBranch++;
            else if (currentBranch == branchIndex && ch is PilotParser.PatternContext pat)
                return pat;
            else if (currentBranch == branchIndex && ch is PilotParser.SuiteContext)
                break;
        }
        return null;
    }

    private static bool HasIfBranchSome(PilotParser.If_stmtContext ctx, int branchIndex)
    {
        int currentBranch = -1;
        for (int i = 0; i < ctx.ChildCount; i++)
        {
            var ch = ctx.GetChild(i);
            if (ch is ITerminalNode term)
            {
                if (term.Symbol.Type == PilotLexer.IF || term.Symbol.Type == PilotLexer.ELIF)
                    currentBranch++;
                else if (currentBranch == branchIndex && term.Symbol.Type == PilotLexer.SOME)
                    return true;
            }
            else if (currentBranch == branchIndex && ch is PilotParser.SuiteContext)
                break;
        }
        return false;
    }

    private static PilotParser.Atom_exprContext? FindFirstAtomExpr(IParseTree node)
    {
        if (node is PilotParser.Atom_exprContext ae) return ae;
        for (int i = 0; i < node.ChildCount; i++)
        {
            var found = FindFirstAtomExpr(node.GetChild(i));
            if (found != null) return found;
        }
        return null;
    }

    private static bool IsNullLiteralText(string text) =>
        text is "none" or "null";

    private static bool IsSimpleIdentifier(string text)
    {
        if (string.IsNullOrEmpty(text)) return false;
        if (!char.IsLetter(text[0]) && text[0] != '_') return false;
        for (int i = 1; i < text.Length; i++)
        {
            if (!char.IsLetterOrDigit(text[i]) && text[i] != '_')
                return false;
        }
        return true;
    }

    private static bool IsKnownBuiltinTypeName(string name) =>
        name is "int" or "float" or "str" or "string" or "bool" or "boolean" or "void" or "any";

    private static string TruncateSource(string text) =>
        text.Length <= 48 ? text : text[..45] + "...";

