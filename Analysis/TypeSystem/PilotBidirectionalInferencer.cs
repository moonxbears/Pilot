    #region Condition Narrowing Extraction (`&&`, `||`, `!`, `!= none`, `is Variant(r)`)

    private (Dictionary<string, PilotType> TrueNarrowing, Dictionary<string, PilotType> FalseNarrowing, Dictionary<string, PilotType> PatternBindings)
        ExtractConditionNarrowing(ParserRuleContext condCtx)
    {
        var trueMap = new Dictionary<string, PilotType>(StringComparer.Ordinal);
        var falseMap = new Dictionary<string, PilotType>(StringComparer.Ordinal);
        var patBinds = new Dictionary<string, PilotType>(StringComparer.Ordinal);

        switch (condCtx)
        {
            case PilotParser.TestContext testCtx:
                if (testCtx.pipe_expr() is { Length: 1 } pipes)
                    return ExtractConditionNarrowing(pipes[0]);
                Synthesize(testCtx);
                return (trueMap, falseMap, patBinds);

            case PilotParser.Pipe_exprContext pipeCtx:
                if (pipeCtx.set_query_expr() is { Length: 1 } sqs)
                    return ExtractConditionNarrowing(sqs[0]);
                Synthesize(pipeCtx);
                return (trueMap, falseMap, patBinds);

            case PilotParser.Set_query_exprContext sqCtx:
                if (sqCtx.coalesce_expr() is { Length: 1 } coal)
                    return ExtractConditionNarrowing(coal[0]);
                Synthesize(sqCtx);
                return (trueMap, falseMap, patBinds);

            case PilotParser.Coalesce_exprContext coalCtx:
                if (coalCtx.or_test() is { Length: 1 } ors && coalCtx.catch_clause().Length == 0)
                    return ExtractConditionNarrowing(ors[0]);
                Synthesize(coalCtx);
                return (trueMap, falseMap, patBinds);

            case PilotParser.Or_testContext orCtx:
            {
                var ands = orCtx.and_test();
                if (ands.Length == 1)
                    return ExtractConditionNarrowing(ands[0]);

                PushFlowScope();
                for (int i = 0; i < ands.Length; i++)
                {
                    var (_, fSub, _) = ExtractConditionNarrowing(ands[i]);
                    foreach (var kvp in fSub)
                    {
                        falseMap[kvp.Key] = kvp.Value;
                        SetFlowNarrowedType(kvp.Key, kvp.Value, ands[i].Start?.Line);
                    }
                }
                PopFlowScope();
                return (trueMap, falseMap, patBinds);
            }

            case PilotParser.And_testContext andCtx:
            {
                var nots = andCtx.not_test();
                if (nots.Length == 1)
                    return ExtractConditionNarrowing(nots[0]);

                PushFlowScope();
                for (int i = 0; i < nots.Length; i++)
                {
                    var (tSub, fSub, pSub) = ExtractConditionNarrowing(nots[i]);
                    foreach (var kvp in tSub)
                    {
                        trueMap[kvp.Key] = kvp.Value;
                        SetFlowNarrowedType(kvp.Key, kvp.Value, nots[i].Start?.Line);
                    }
                    foreach (var kvp in pSub)
                    {
                        patBinds[kvp.Key] = kvp.Value;
                        _engine.SetVariableType(kvp.Key, kvp.Value);
                        SetFlowNarrowedType(kvp.Key, kvp.Value, nots[i].Start?.Line);
                    }
                    if (i == 0)
                    {
                        foreach (var kvp in fSub)
                            falseMap[kvp.Key] = kvp.Value;
                    }
                }
                PopFlowScope();
                return (trueMap, falseMap, patBinds);
            }

            case PilotParser.Not_testContext notCtx:
            {
                if (notCtx.NOT() != null && notCtx.not_test() != null)
                {
                    var (innerTrue, innerFalse, _) = ExtractConditionNarrowing(notCtx.not_test());
                    return (innerFalse, innerTrue, patBinds);
                }
                if (notCtx.comparison() != null)
                    return ExtractConditionNarrowing(notCtx.comparison());
                return (trueMap, falseMap, patBinds);
            }

            case PilotParser.ComparisonContext compCtx:
            {
                SynthesizeComparison(compCtx);
                var ranges = compCtx.range_expr();
                if (ranges.Length >= 1)
                {
                    string lhsText = ranges[0].GetText().Trim();
                    if (compCtx.pattern() is { Length: > 0 } pats)
                    {
                        bool isNegated = compCtx.NOT().Length > 0;
                        var lhsType = LookupFlowAwareType(lhsText, compCtx.Start?.Line);
                        if (TryExtractPatternNarrowedType(pats[0], lhsType, out var matchedType, patBinds))
                        {
                            var subtracted = SubtractAdtOrUnionVariant(lhsType, matchedType);
                            if (IsSimpleIdentifier(lhsText))
                            {
                                if (!isNegated)
                                {
                                    trueMap[lhsText] = matchedType;
                                    falseMap[lhsText] = subtracted;
                                }
                                else
                                {
                                    trueMap[lhsText] = subtracted;
                                    falseMap[lhsText] = matchedType;
                                    patBinds.Clear();
                                }
                            }
                        }
                        return (trueMap, falseMap, patBinds);
                    }

                    if (ranges.Length == 2 && compCtx.comp_op() is { Length: 1 } ops)
                    {
                        string opText = ops[0].GetText();
                        string rhsText = ranges[1].GetText().Trim();
                        string? targetVar = null;
                        bool comparedWithNull = false;

                        if (IsNullLiteralText(rhsText) && IsSimpleIdentifier(lhsText))
                        {
                            targetVar = lhsText;
                            comparedWithNull = true;
                        }
                        else if (IsNullLiteralText(lhsText) && IsSimpleIdentifier(rhsText))
                        {
                            targetVar = rhsText;
                            comparedWithNull = true;
                        }

                        if (comparedWithNull && targetVar != null)
                        {
                            var origType = LookupFlowAwareType(targetVar, compCtx.Start?.Line);
                            var nonNullType = origType.SubtractType(PilotType.Null);
                            if (opText == "!=")
                            {
                                trueMap[targetVar] = nonNullType;
                                falseMap[targetVar] = PilotType.Null;
                            }
                            else if (opText == "==")
                            {
                                trueMap[targetVar] = PilotType.Null;
                                falseMap[targetVar] = nonNullType;
                            }
                        }
                    }
                }
                return (trueMap, falseMap, patBinds);
            }
        }

        return (trueMap, falseMap, patBinds);
    }

    private PilotType SubtractAdtOrUnionVariant(PilotType originalType, PilotType matchedVariant)
    {
        if (originalType.Kind == PilotTypeKind.Union || originalType.Kind == PilotTypeKind.Option)
        {
            return originalType.SubtractType(matchedVariant);
        }

        if (_nominalLayouts.TryGetValue(originalType.Name, out var adtLayout) && adtLayout.AdtVariants.Count > 1)
        {
            var remaining = adtLayout.AdtVariants
                .Where(v => !string.Equals(v, matchedVariant.Name, StringComparison.OrdinalIgnoreCase))
                .Select(v => new PilotType(PilotTypeKind.Primitive, v))
                .ToArray();
            if (remaining.Length == 1) return remaining[0];
            if (remaining.Length > 1) return PilotType.UnionOf(remaining);
        }

        return originalType;
    }

    private bool TryExtractPatternNarrowedType(
        PilotParser.PatternContext pattern,
        PilotType scrutineeType,
        out PilotType narrowedType,
        Dictionary<string, PilotType>? patternBindings = null)
    {
        narrowedType = scrutineeType;
        string patText = pattern.GetText().Trim();
        if (IsNullLiteralText(patText))
        {
            narrowedType = PilotType.Null;
            return true;
        }

        var prim = FindFirstPrimaryPattern(pattern);
        if (prim?.type_or_var_pattern() is { } tvp)
        {
            string headName = tvp.dotted_name().GetText();
            if (headName.Contains('.'))
                headName = headName[(headName.LastIndexOf('.') + 1)..];

            if (string.Equals(headName, "some", StringComparison.OrdinalIgnoreCase))
            {
                narrowedType = scrutineeType.SubtractType(PilotType.Null);
                if (tvp.pattern_arg() is { Length: > 0 } sArgs && patternBindings != null)
                {
                    string boundVar = sArgs[0].pattern().GetText().Trim();
                    if (IsSimpleIdentifier(boundVar))
                        patternBindings[boundVar] = narrowedType;
                }
                return true;
            }

            if (_nominalLayouts.TryGetValue(headName, out var layout))
            {
                narrowedType = layout.NominalType;
                if (tvp.pattern_arg() is { } args && patternBindings != null)
                {
                    for (int i = 0; i < args.Length && i < layout.OrderedFields.Count; i++)
                    {
                        string argVar = args[i].pattern().GetText().Trim();
                        if (IsSimpleIdentifier(argVar) && argVar != "_")
                        {
                            patternBindings[argVar] = layout.OrderedFields[i].Type;
                        }
                    }
                }
                return true;
            }

            var parsed = PilotTypeInferenceEngine.ParseTypeString(headName);
            if (parsed.Kind != PilotTypeKind.Primitive || IsKnownBuiltinTypeName(headName))
            {
                narrowedType = parsed;
                return true;
            }
        }

        return false;
    }

    private void BindMatchPatternVariables(PilotParser.PatternContext pattern, PilotType scrutineeType, int? line)
    {
        var bindings = new Dictionary<string, PilotType>(StringComparer.Ordinal);
        if (TryExtractPatternNarrowedType(pattern, scrutineeType, out _, bindings))
        {
            foreach (var kvp in bindings)
            {
                _engine.SetVariableType(kvp.Key, kvp.Value);
                SetFlowNarrowedType(kvp.Key, kvp.Value, line);
            }
            return;
        }

        string text = pattern.GetText().Trim();
        if (text.StartsWith("some", StringComparison.Ordinal) && text.Length > 4)
        {
            string rest = text[4..].Trim().Trim('(', ')');
            if (IsSimpleIdentifier(rest))
            {
                var unwrapped = scrutineeType.SubtractType(PilotType.Null);
                _engine.SetVariableType(rest, unwrapped);
                SetFlowNarrowedType(rest, unwrapped, line);
                return;
            }
        }

        if (IsSimpleIdentifier(text) && text != "_" && !IsNullLiteralText(text) && !_nominalLayouts.ContainsKey(text))
        {
            _engine.SetVariableType(text, scrutineeType);
            SetFlowNarrowedType(text, scrutineeType, line);
        }
    }

    private static PilotParser.Primary_patternContext? FindFirstPrimaryPattern(IParseTree node)
    {
        if (node is PilotParser.Primary_patternContext pp) return pp;
        for (int i = 0; i < node.ChildCount; i++)
        {
            var found = FindFirstPrimaryPattern(node.GetChild(i));
            if (found != null) return found;
        }
        return null;
    }

