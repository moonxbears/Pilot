    #region Pass 2: Tarjan Strongly Connected Components (SCC) Fixed-Point Unification

    private void SolveFunctionSccs(PilotParser.ProgramContext program)
    {
        var allFuncs = _schemesByNode.Values.ToList();
        if (allFuncs.Count == 0) return;

        var edges = new Dictionary<PilotFunctionScheme, HashSet<PilotFunctionScheme>>();
        foreach (var sc in allFuncs)
        {
            var callees = new HashSet<PilotFunctionScheme>();
            if (sc.Context.suite() != null)
            {
                CollectCalledSchemes(sc.Context.suite(), callees);
            }
            edges[sc] = callees;
        }

        var sccs = ComputeTarjanSccs(allFuncs, edges);

        bool prevSuppress = _suppressDiagnostics;
        _suppressDiagnostics = true;
        try
        {
            foreach (var scc in sccs)
            {
                SolveSingleSccFixedPoint(scc);
            }
        }
        finally
        {
            _suppressDiagnostics = prevSuppress;
        }
    }

    private void CollectCalledSchemes(IParseTree node, HashSet<PilotFunctionScheme> callees)
    {
        if (node is PilotParser.Atom_exprContext atomExpr)
        {
            var trailers = atomExpr.trailer();
            if (trailers != null && trailers.Length > 0 && trailers[0].LPAR() != null && atomExpr.atom()?.identifier() is { } idCtx)
            {
                string calleeName = idCtx.GetText();
                if (_functionGroups.TryGetValue(calleeName, out var group))
                {
                    foreach (var target in group)
                        callees.Add(target);
                }
            }
        }

        for (int i = 0; i < node.ChildCount; i++)
        {
            CollectCalledSchemes(node.GetChild(i), callees);
        }
    }

    private static List<List<PilotFunctionScheme>> ComputeTarjanSccs(
        List<PilotFunctionScheme> nodes,
        Dictionary<PilotFunctionScheme, HashSet<PilotFunctionScheme>> edges)
    {
        int index = 0;
        var indices = new Dictionary<PilotFunctionScheme, int>();
        var lowlink = new Dictionary<PilotFunctionScheme, int>();
        var onStack = new HashSet<PilotFunctionScheme>();
        var stack = new Stack<PilotFunctionScheme>();
        var result = new List<List<PilotFunctionScheme>>();

        void StrongConnect(PilotFunctionScheme v)
        {
            indices[v] = index;
            lowlink[v] = index;
            index++;
            stack.Push(v);
            onStack.Add(v);

            if (edges.TryGetValue(v, out var neighbors))
            {
                foreach (var w in neighbors)
                {
                    if (!indices.ContainsKey(w))
                    {
                        StrongConnect(w);
                        lowlink[v] = Math.Min(lowlink[v], lowlink[w]);
                    }
                    else if (onStack.Contains(w))
                    {
                        lowlink[v] = Math.Min(lowlink[v], indices[w]);
                    }
                }
            }

            if (lowlink[v] == indices[v])
            {
                var scc = new List<PilotFunctionScheme>();
                PilotFunctionScheme w;
                do
                {
                    w = stack.Pop();
                    onStack.Remove(w);
                    scc.Add(w);
                } while (!ReferenceEquals(w, v));
                result.Add(scc);
            }
        }

        foreach (var node in nodes)
        {
            if (!indices.ContainsKey(node))
            {
                StrongConnect(node);
            }
        }

        return result;
    }

    private void SolveSingleSccFixedPoint(List<PilotFunctionScheme> scc)
    {
        const int maxIterations = 6;
        for (int iter = 0; iter < maxIterations; iter++)
        {
            bool changed = false;

            foreach (var scheme in scc)
            {
                var beforeType = scheme.BuildFunctionType(_engine.Substitutions);
                int beforeErrCount = scheme.InferredErrorVariants.Count;

                InferSchemeOnce(scheme);

                var afterType = scheme.BuildFunctionType(_engine.Substitutions);
                _engine.SetVariableType(scheme.Name, afterType);

                if (!beforeType.Equals(afterType) || scheme.InferredErrorVariants.Count != beforeErrCount)
                {
                    changed = true;
                }
            }

            if (!changed)
                break;
        }

        foreach (var scheme in scc)
        {
            var resolvedRet = _engine.ResolveType(scheme.ReturnType);
            if (!scheme.HasExplicitReturnType &&
                scheme.Context.FAT_ARROW() == null &&
                resolvedRet.Kind == PilotTypeKind.TypeVariable &&
                resolvedRet.TypeVarConstraint == PilotTypeClassConstraint.None &&
                !IsTypeVariableReferencedInParameters(scheme, resolvedRet.TypeVarId))
            {
                _engine.Substitutions[resolvedRet.TypeVarId] = PilotType.Void;
                scheme.ReturnType = PilotType.Void;
            }
            _engine.SetVariableType(scheme.Name, scheme.BuildFunctionType(_engine.Substitutions));
        }
    }

    private bool IsTypeVariableReferencedInParameters(PilotFunctionScheme scheme, int typeVarId)
    {
        foreach (var p in scheme.ParameterTypes)
        {
            if (PilotType.OccursIn(typeVarId, _engine.ResolveType(p), _engine.Substitutions))
                return true;
        }
        foreach (var rowMap in scheme.RowParameterFields.Values)
        {
            foreach (var fType in rowMap.Values)
            {
                if (PilotType.OccursIn(typeVarId, _engine.ResolveType(fType), _engine.Substitutions))
                    return true;
            }
        }
        return false;
    }

    private void InferSchemeOnce(PilotFunctionScheme scheme)
    {
        if (scheme.Context.suite() == null) return;

        _engine.PushScope();
        PushFlowScope();
        _activeSchemeStack.Push(scheme);

        for (int i = 0; i < scheme.ParameterNames.Count; i++)
        {
            _engine.SetVariableType(scheme.ParameterNames[i], _engine.ResolveType(scheme.ParameterTypes[i]));
        }

        var returnTypes = new List<PilotType>();
        _expectedReturnStack.Push(scheme.HasExplicitReturnType ? scheme.ReturnType : null);

        var bodyType = AnalyzeSuiteForReturn(scheme.Context.suite(), returnTypes);

        _expectedReturnStack.Pop();
        _activeSchemeStack.Pop();
        PopFlowScope();
        _engine.PopScope();

        var concreteReturns = returnTypes
            .Select(_engine.ResolveType)
            .Where(t => t.Kind != PilotTypeKind.TypeVariable && t != PilotType.Any)
            .ToList();

        var typeVarReturns = returnTypes
            .Select(_engine.ResolveType)
            .Where(t => t.Kind == PilotTypeKind.TypeVariable && t.TypeVarId != scheme.ReturnType.TypeVarId)
            .ToList();

        if (concreteReturns.Count == 0 && bodyType != PilotType.Void && bodyType != PilotType.Any)
        {
            var resolvedBody = _engine.ResolveType(bodyType);
            if (resolvedBody.Kind != PilotTypeKind.TypeVariable)
                concreteReturns.Add(resolvedBody);
            else if (scheme.Context.FAT_ARROW() != null)
                concreteReturns.Add(resolvedBody);
        }

        if (!scheme.HasExplicitReturnType)
        {
            if (concreteReturns.Count == 1)
            {
                scheme.ReturnType.Unify(concreteReturns[0], _engine.Substitutions);
                scheme.ReturnType = _engine.ResolveType(scheme.ReturnType);
            }
            else if (concreteReturns.Count > 1)
            {
                var unified = JoinTypes(concreteReturns);
                if (scheme.ReturnType.Kind == PilotTypeKind.TypeVariable)
                    _engine.Substitutions[scheme.ReturnType.TypeVarId] = unified;
                scheme.ReturnType = unified;
            }
            else if (typeVarReturns.Count > 0)
            {
                scheme.ReturnType.Unify(typeVarReturns[0], _engine.Substitutions);
                scheme.ReturnType = _engine.ResolveType(scheme.ReturnType);
            }
            else if (scheme.Context.FAT_ARROW() != null && bodyType.Kind == PilotTypeKind.TypeVariable)
            {
                scheme.ReturnType.Unify(bodyType, _engine.Substitutions);
                scheme.ReturnType = _engine.ResolveType(scheme.ReturnType);
            }
        }
    }

    private void AnalyzeFunctionBodyFinal(PilotParser.Func_defContext fnDef)
    {
        if (!_schemesByNode.TryGetValue(fnDef, out var scheme))
            return;

        _engine.PushScope();
        PushFlowScope();
        _activeSchemeStack.Push(scheme);

        var parameters = fnDef.parameters()?.parameter();
        for (int i = 0; i < scheme.ParameterNames.Count; i++)
        {
            PilotType finalParamType = _engine.ResolveType(scheme.ParameterTypes[i]);
            if (scheme.RowParameterFields.TryGetValue(i, out var rowFields) && rowFields.Count > 0)
            {
                var resolvedRow = new Dictionary<string, PilotType>(StringComparer.Ordinal);
                foreach (var kvp in rowFields)
                    resolvedRow[kvp.Key] = _engine.ResolveType(kvp.Value);
                finalParamType = PilotType.RowRecordOf(resolvedRow, isOpenRow: true, rowTailName: "R");
            }
            _engine.SetVariableType(scheme.ParameterNames[i], finalParamType);
            _engine.RecordGlobalInferredType($"{scheme.Name}.{scheme.ParameterNames[i]}", finalParamType);

            if (!scheme.ParameterHasExplicitType[i] && parameters != null && i < parameters.Length)
            {
                var pId = parameters[i].identifier()?.Start;
                if (pId != null && finalParamType.Kind != PilotTypeKind.Any)
                {
                    AddInlayHint(
                        pId.Line - 1,
                        pId.Column + (pId.Text?.Length ?? 0),
                        $": {finalParamType}",
                        PilotInlayHintKind.Type,
                        tooltip: $"Inferred parameter type for '{scheme.ParameterNames[i]}'");
                }
            }
        }

        var fullFnType = scheme.BuildFunctionType(_engine.Substitutions);
        var expectedRet = fullFnType.ReturnType ?? PilotType.Void;
        _expectedReturnStack.Push(scheme.HasExplicitReturnType ? scheme.ReturnType : expectedRet);

        if (fnDef.suite() != null)
        {
            if (fnDef.FAT_ARROW() != null && scheme.HasExplicitReturnType)
            {
                var retOrigin = PilotSourceSpan.FromContext(fnDef.type_spec(), $"return type of function '{scheme.Name}'");
                CheckSuite(fnDef.suite(), scheme.ReturnType, retOrigin);
            }
            else
            {
                var ignored = new List<PilotType>();
                AnalyzeSuiteForReturn(fnDef.suite(), ignored);
            }
        }

        _expectedReturnStack.Pop();
        _activeSchemeStack.Pop();
        PopFlowScope();
        _engine.PopScope();

        if ((!scheme.HasExplicitReturnType || scheme.HasOpenErrorMarker) && fnDef.parameters()?.Stop is { } rparTok)
        {
            var finalRet = fullFnType.ReturnType ?? PilotType.Void;
            if (!scheme.HasExplicitReturnType && finalRet.Kind != PilotTypeKind.Any)
            {
                AddInlayHint(
                    rparTok.Line - 1,
                    rparTok.Column + 1,
                    $" -> {finalRet}",
                    PilotInlayHintKind.Type,
                    paddingLeft: true,
                    tooltip: $"Inferred return type for '{scheme.Name}'");
            }
            else if (scheme.HasOpenErrorMarker && finalRet.IsResult && fnDef.type_spec()?.Stop is { } bangTok)
            {
                AddInlayHint(
                    bangTok.Line - 1,
                    bangTok.Column + 1,
                    $" {finalRet.TypeArguments[1]}",
                    PilotInlayHintKind.Type,
                    paddingLeft: true,
                    tooltip: $"Inferred error set for '{scheme.Name}'");
            }
        }

        _engine.SetVariableType(scheme.Name, fullFnType);
    }

