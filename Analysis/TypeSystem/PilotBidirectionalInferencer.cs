    #region Statements & Dominator Control-Flow Narrowing (16.2)

    private void PushFlowScope()
    {
        var current = _flowNarrowingStack.Count > 0
            ? new Dictionary<string, PilotType>(_flowNarrowingStack.Peek(), StringComparer.Ordinal)
            : new Dictionary<string, PilotType>(StringComparer.Ordinal);
        _flowNarrowingStack.Push(current);
    }

    private Dictionary<string, PilotType> PopFlowScope() =>
        _flowNarrowingStack.Count > 1 ? _flowNarrowingStack.Pop() : _flowNarrowingStack.Peek();

    private void SetFlowNarrowedType(string name, PilotType narrowedType, int? line = null)
    {
        var resolved = _engine.ResolveType(narrowedType);
        _flowNarrowingStack.Peek()[name] = resolved;
        if (line.HasValue)
        {
            _lineFlowTypes[(line.Value, name)] = resolved;
        }
    }

    private PilotType LookupFlowAwareType(string name, int? line = null)
    {
        if (_flowNarrowingStack.Count > 0 && _flowNarrowingStack.Peek().TryGetValue(name, out var narrowed))
        {
            var resolved = _engine.ResolveType(narrowed);
            if (line.HasValue)
                _lineFlowTypes[(line.Value, name)] = resolved;
            return resolved;
        }
        if (_engine.TryLookupType(name, out var envType))
        {
            var resolved = _engine.ResolveType(envType);
            if (line.HasValue)
                _lineFlowTypes[(line.Value, name)] = resolved;
            return resolved;
        }
        return PilotType.Any;
    }

    private PilotType AnalyzeSuiteForReturn(PilotParser.SuiteContext suite, List<PilotType> returnTypes)
    {
        if (suite.simple_stmt() is { } simple)
        {
            return AnalyzeSimpleStmt(simple, returnTypes);
        }

        PilotType lastType = PilotType.Void;
        var stmts = suite.stmt();
        if (stmts != null)
        {
            for (int i = 0; i < stmts.Length; i++)
            {
                lastType = AnalyzeStatement(stmts[i], returnTypes);
            }
        }
        return lastType;
    }

    private PilotType CheckSuite(PilotParser.SuiteContext suite, PilotType expectedType, PilotSourceSpan expectedOrigin)
    {
        if (suite.simple_stmt() is { } simple)
        {
            var smalls = simple.small_stmt();
            if (smalls != null && smalls.Length == 1 && smalls[0].expr_stmt() is { } exprStmt &&
                exprStmt.EQUAL().Length == 0 && exprStmt.augassign().Length == 0 && exprStmt.WALRUS().Length == 0)
            {
                var tests = exprStmt.testlist()?.test();
                if (tests != null && tests.Length == 1)
                {
                    return Check(tests[0], expectedType, expectedOrigin);
                }
            }
            return AnalyzeSimpleStmt(simple, null);
        }

        var stmts = suite.stmt();
        if (stmts == null || stmts.Length == 0) return PilotType.Void;
        for (int i = 0; i < stmts.Length - 1; i++)
        {
            AnalyzeStatement(stmts[i], null);
        }
        var last = stmts[^1];
        if (last.simple_stmt()?.small_stmt() is { Length: 1 } lastSmalls &&
            lastSmalls[0].expr_stmt() is { } lastExpr &&
            lastExpr.EQUAL().Length == 0 && lastExpr.augassign().Length == 0 && lastExpr.WALRUS().Length == 0 &&
            lastExpr.testlist()?.test() is { Length: 1 } lastTests)
        {
            return Check(lastTests[0], expectedType, expectedOrigin);
        }
        return AnalyzeStatement(last, null);
    }

    private PilotType AnalyzeStatement(PilotParser.StmtContext stmt, List<PilotType>? returnTypes = null)
    {
        if (stmt.simple_stmt() is { } simple)
            return AnalyzeSimpleStmt(simple, returnTypes);

        if (stmt.compound_stmt() is { } comp)
            return AnalyzeCompoundStmt(comp, returnTypes);

        return PilotType.Void;
    }

    private PilotType AnalyzeSimpleStmt(PilotParser.Simple_stmtContext simple, List<PilotType>? returnTypes)
    {
        PilotType last = PilotType.Void;
        var smalls = simple.small_stmt();
        if (smalls == null) return last;

        foreach (var sm in smalls)
        {
            if (sm.let_stmt() is { } ls)
                last = AnalyzeVarDecl(ls.binding_pattern(), ls.type_annotation(), ls.test(), ls);
            else if (sm.var_stmt() is { } vs)
                last = AnalyzeVarDecl(vs.binding_pattern(), vs.type_annotation(), vs.test(), vs);
            else if (sm.const_stmt() is { } cs)
                last = AnalyzeVarDecl(cs.binding_pattern(), cs.type_annotation(), cs.test(), cs);
            else if (sm.guard_stmt() is { } gs)
                AnalyzeGuardStmt(gs, returnTypes);
            else if (sm.flow_stmt() is { } fs)
                last = AnalyzeFlowStmt(fs, returnTypes);
            else if (sm.expr_stmt() is { } es)
                last = AnalyzeExprStmt(es);
        }
        return last;
    }

    private PilotType AnalyzeCompoundStmt(PilotParser.Compound_stmtContext comp, List<PilotType>? returnTypes)
    {
        if (comp.guard_stmt() is { } guardStmt)
        {
            AnalyzeGuardStmt(guardStmt, returnTypes);
            return PilotType.Void;
        }
        if (comp.if_stmt() is { } ifStmt)
            return AnalyzeIfStmt(ifStmt, expectedType: null, expectedOrigin: null, returnTypes);
        if (comp.match_stmt() is { } matchStmt)
            return AnalyzeMatchStmt(matchStmt, expectedType: null, expectedOrigin: null, returnTypes);
        if (comp.for_stmt() is { } forStmt)
            return AnalyzeForStmt(forStmt, expectedType: null, expectedOrigin: null, returnTypes);
        if (comp.while_stmt() is { } whileStmt)
        {
            if (whileStmt.test() is { Length: > 0 } wTests) Synthesize(wTests[0]);
            if (whileStmt.suite() is { Length: > 0 } suites)
            {
                _engine.PushScope();
                PushFlowScope();
                AnalyzeSuiteForReturn(suites[0], returnTypes ?? new List<PilotType>());
                PopFlowScope();
                _engine.PopScope();
            }
            return PilotType.Void;
        }
        if (comp.func_def() is { } fnDef)
        {
            if (!_schemesByNode.ContainsKey(fnDef))
            {
                RegisterFunctionStub(fnDef);
                InferSchemeOnce(_schemesByNode[fnDef]);
            }
            AnalyzeFunctionBodyFinal(fnDef);
            return _engine.TryLookupType(fnDef.identifier().GetText(), out var ft) ? ft : PilotType.Void;
        }
        return PilotType.Void;
    }

    private PilotType AnalyzeVarDecl(
        PilotParser.Binding_patternContext? pattern,
        PilotParser.Type_annotationContext? typeAnn,
        PilotParser.TestContext? rhs,
        ParserRuleContext declCtx)
    {
        string name = pattern?.identifier()?.GetText() ?? "";
        var idTok = pattern?.identifier()?.Start;
        return AnalyzeVarDecl(name, typeAnn, rhs, declCtx, idTok, pattern);
    }

    private PilotType AnalyzeVarDecl(
        string name,
        PilotParser.Type_annotationContext? typeAnn,
        PilotParser.TestContext? rhs,
        ParserRuleContext declCtx,
        IToken? idTok = null,
        PilotParser.Binding_patternContext? bindingPattern = null)
    {
        string declaredStr = typeAnn?.type_spec()?.GetText() ?? "";
        PilotType? declaredType = !string.IsNullOrEmpty(declaredStr)
            ? PilotTypeInferenceEngine.ParseTypeString(declaredStr)
            : null;

        PilotType inferredRhs = PilotType.Any;
        if (rhs != null)
        {
            if (declaredType != null)
            {
                var origin = PilotSourceSpan.FromContext(typeAnn!.type_spec(), $"type annotation on '{name}'");
                inferredRhs = Check(rhs, declaredType, origin);
            }
            else
            {
                inferredRhs = Synthesize(rhs);
            }
        }

        PilotType finalType = declaredType ?? inferredRhs;
        if (declaredType != null &&
            string.IsNullOrEmpty(declaredType.ActiveTypestate) &&
            !string.IsNullOrEmpty(inferredRhs.ActiveTypestate) &&
            string.Equals(declaredType.Name, inferredRhs.Name, StringComparison.OrdinalIgnoreCase))
        {
            finalType = PilotType.WithTypestate(declaredType, inferredRhs.ActiveTypestate!);
        }

        if (!string.IsNullOrEmpty(name))
        {
            if (declCtx is PilotParser.Var_stmtContext)
            {
                _mutableVariableNames.Add(name);
            }
            _engine.SetVariableType(name, finalType);
            SetFlowNarrowedType(name, finalType, declCtx.Start?.Line);

            if (declaredType == null && idTok != null && finalType.Kind != PilotTypeKind.Any && finalType.Kind != PilotTypeKind.Void)
            {
                AddInlayHint(
                    idTok.Line - 1,
                    idTok.Column + (idTok.Text?.Length ?? name.Length),
                    $": {finalType}",
                    PilotInlayHintKind.Type,
                    tooltip: $"Inferred type for '{name}'");
            }
        }
        else if (bindingPattern != null)
        {
            BindDestructuringPattern(bindingPattern, finalType);
        }

        return finalType;
    }

    private void BindDestructuringPattern(PilotParser.Binding_patternContext pattern, PilotType valueType)
    {
        if (pattern.tuple_pattern()?.binding_pattern_item() is { } tupleItems)
        {
            for (int i = 0; i < tupleItems.Length; i++)
            {
                var elemType = valueType.Kind == PilotTypeKind.Tuple && i < valueType.TypeArguments.Count
                    ? valueType.TypeArguments[i]
                    : (valueType.Kind == PilotTypeKind.Collection && valueType.TypeArguments.Count > 0 ? valueType.TypeArguments[0] : PilotType.Any);
                string? bName = tupleItems[i].binding_pattern()?.identifier()?.GetText();
                if (!string.IsNullOrEmpty(bName))
                {
                    _engine.SetVariableType(bName, elemType);
                    SetFlowNarrowedType(bName, elemType, pattern.Start?.Line);
                }
            }
        }
        else if (pattern.record_pattern()?.record_pattern_field() is { } recFields)
        {
            foreach (var rf in recFields)
            {
                string fName = rf.identifier().GetText();
                PilotType fType = LookupFieldType(valueType, fName);
                string targetVar = rf.binding_pattern()?.identifier()?.GetText() ?? fName;
                _engine.SetVariableType(targetVar, fType);
                SetFlowNarrowedType(targetVar, fType, pattern.Start?.Line);
            }
        }
    }

    private void AnalyzeGuardStmt(PilotParser.Guard_stmtContext ctx, List<PilotType>? returnTypes)
    {
        var testCtx = ctx.test();
        var patCtx = ctx.pattern();
        var suiteCtx = ctx.suite();

        if (patCtx != null && testCtx != null)
        {
            var rhsType = Synthesize(testCtx);
            var unwrapped = rhsType.Kind == PilotTypeKind.Option && rhsType.TypeArguments.Count == 1
                ? rhsType.TypeArguments[0]
                : (rhsType.IsResult ? rhsType.TypeArguments[0] : rhsType);

            if (suiteCtx != null)
            {
                _engine.PushScope();
                PushFlowScope();
                if (ctx.CATCH() != null && ctx.identifier() != null && rhsType.IsResult)
                {
                    var errType = rhsType.TypeArguments[1];
                    _engine.SetVariableType(ctx.identifier().GetText(), errType);
                    SetFlowNarrowedType(ctx.identifier().GetText(), errType, ctx.Start?.Line);
                }
                AnalyzeSuiteForReturn(suiteCtx, returnTypes ?? new List<PilotType>());
                PopFlowScope();
                _engine.PopScope();
            }

            BindMatchPatternVariables(patCtx, unwrapped, ctx.Start?.Line);
            return;
        }

        if (testCtx != null)
        {
            if (ctx.SOME() != null)
            {
                string varName = testCtx.GetText().Trim();
                var origType = LookupFlowAwareType(varName, ctx.Start?.Line);
                var narrowed = origType.SubtractType(PilotType.Null);

                if (suiteCtx != null)
                {
                    _engine.PushScope();
                    PushFlowScope();
                    SetFlowNarrowedType(varName, PilotType.Null, suiteCtx.Start?.Line);
                    AnalyzeSuiteForReturn(suiteCtx, returnTypes ?? new List<PilotType>());
                    PopFlowScope();
                    _engine.PopScope();
                }

                SetFlowNarrowedType(varName, narrowed, (ctx.Stop?.Line ?? ctx.Start.Line) + 1);
                return;
            }

            var (trueNarrow, falseNarrow, patBinds) = ExtractConditionNarrowing(testCtx);
            if (suiteCtx != null)
            {
                _engine.PushScope();
                PushFlowScope();
                foreach (var kvp in falseNarrow)
                    SetFlowNarrowedType(kvp.Key, kvp.Value, suiteCtx.Start?.Line);
                AnalyzeSuiteForReturn(suiteCtx, returnTypes ?? new List<PilotType>());
                PopFlowScope();
                _engine.PopScope();
            }

            int contLine = (ctx.Stop?.Line ?? ctx.Start.Line) + 1;
            foreach (var kvp in trueNarrow)
                SetFlowNarrowedType(kvp.Key, kvp.Value, contLine);
            foreach (var kvp in patBinds)
            {
                _engine.SetVariableType(kvp.Key, kvp.Value);
                SetFlowNarrowedType(kvp.Key, kvp.Value, contLine);
            }
        }
    }

    private PilotType AnalyzeIfStmt(
        PilotParser.If_stmtContext ctx,
        PilotType? expectedType,
        PilotSourceSpan? expectedOrigin,
        List<PilotType>? returnTypes)
    {
        var suites = ctx.suite();
        var tests = ctx.test();
        if (suites == null || suites.Length == 0) return PilotType.Void;

        var branchResultTypes = new List<PilotType>();
        var survivingBranchFlows = new List<Dictionary<string, PilotType>>();
        var accumulatedFalseNarrowing = new Dictionary<string, PilotType>(StringComparer.Ordinal);

        int testCount = tests?.Length ?? 0;
        for (int i = 0; i < testCount && i < suites.Length; i++)
        {
            _engine.PushScope();
            PushFlowScope();

            foreach (var kvp in accumulatedFalseNarrowing)
                SetFlowNarrowedType(kvp.Key, kvp.Value, suites[i].Start?.Line);

            var branchPat = FindIfBranchPattern(ctx, i);
            bool hasSome = HasIfBranchSome(ctx, i);
            Dictionary<string, PilotType> branchFalseNarrow;

            if (branchPat != null)
            {
                var rhsType = Synthesize(tests![i]);
                var unwrapped = rhsType.Kind == PilotTypeKind.Option && rhsType.TypeArguments.Count == 1
                    ? rhsType.TypeArguments[0]
                    : rhsType;
                BindMatchPatternVariables(branchPat, unwrapped, suites[i].Start?.Line);
                string rhsVar = tests[i].GetText().Trim();
                branchFalseNarrow = new Dictionary<string, PilotType>(StringComparer.Ordinal);
                if (IsSimpleIdentifier(rhsVar))
                    branchFalseNarrow[rhsVar] = rhsType.SubtractType(unwrapped);
            }
            else if (hasSome)
            {
                string varName = tests![i].GetText().Trim();
                var origType = LookupFlowAwareType(varName, tests[i].Start?.Line);
                var unwrapped = origType.SubtractType(PilotType.Null);
                SetFlowNarrowedType(varName, unwrapped, suites[i].Start?.Line);
                branchFalseNarrow = new Dictionary<string, PilotType>(StringComparer.Ordinal)
                {
                    [varName] = PilotType.Null
                };
            }
            else
            {
                var (trueNarrow, falseNarrow, patBinds) = ExtractConditionNarrowing(tests![i]);
                foreach (var kvp in trueNarrow)
                    SetFlowNarrowedType(kvp.Key, kvp.Value, suites[i].Start?.Line);
                foreach (var kvp in patBinds)
                {
                    _engine.SetVariableType(kvp.Key, kvp.Value);
                    SetFlowNarrowedType(kvp.Key, kvp.Value, suites[i].Start?.Line);
                }
                branchFalseNarrow = falseNarrow;
            }

            PilotType branchType = expectedType != null && expectedOrigin != null
                ? CheckSuite(suites[i], expectedType, expectedOrigin)
                : AnalyzeSuiteForReturn(suites[i], returnTypes ?? new List<PilotType>());
            branchResultTypes.Add(branchType);

            var branchEndFlow = PopFlowScope();
            _engine.PopScope();

            if (!SuiteAlwaysExits(suites[i]))
            {
                survivingBranchFlows.Add(branchEndFlow);
            }

            foreach (var kvp in branchFalseNarrow)
            {
                accumulatedFalseNarrowing[kvp.Key] = kvp.Value;
            }
        }

        bool hasElse = ctx.ELSE() != null && suites.Length > testCount;
        if (hasElse)
        {
            var elseSuite = suites[^1];
            _engine.PushScope();
            PushFlowScope();

            foreach (var kvp in accumulatedFalseNarrowing)
                SetFlowNarrowedType(kvp.Key, kvp.Value, elseSuite.Start?.Line);

            PilotType elseType = expectedType != null && expectedOrigin != null
                ? CheckSuite(elseSuite, expectedType, expectedOrigin)
                : AnalyzeSuiteForReturn(elseSuite, returnTypes ?? new List<PilotType>());
            branchResultTypes.Add(elseType);

            var elseEndFlow = PopFlowScope();
            _engine.PopScope();

            if (!SuiteAlwaysExits(elseSuite))
            {
                survivingBranchFlows.Add(elseEndFlow);
            }
        }
        else
        {
            var implicitElseFlow = new Dictionary<string, PilotType>(_flowNarrowingStack.Peek(), StringComparer.Ordinal);
            foreach (var kvp in accumulatedFalseNarrowing)
                implicitElseFlow[kvp.Key] = kvp.Value;
            survivingBranchFlows.Add(implicitElseFlow);
        }

        int afterLine = (ctx.Stop?.Line ?? ctx.Start.Line) + 1;
        if (survivingBranchFlows.Count == 1)
        {
            foreach (var kvp in survivingBranchFlows[0])
                SetFlowNarrowedType(kvp.Key, kvp.Value, afterLine);
        }
        else if (survivingBranchFlows.Count > 1)
        {
            var allKeys = survivingBranchFlows.SelectMany(d => d.Keys).Distinct(StringComparer.Ordinal).ToList();
            foreach (var key in allKeys)
            {
                var candidateTypes = new List<PilotType>();
                foreach (var flow in survivingBranchFlows)
                {
                    if (flow.TryGetValue(key, out var ft))
                        candidateTypes.Add(ft);
                    else if (_engine.TryLookupType(key, out var baseT))
                        candidateTypes.Add(baseT);
                }
                if (candidateTypes.Count > 0)
                {
                    SetFlowNarrowedType(key, JoinTypes(candidateTypes), afterLine);
                }
            }
        }

        var resultType = branchResultTypes.Count > 0 ? JoinTypes(branchResultTypes) : PilotType.Void;
        _nodeTypes[ctx] = resultType;
        return resultType;
    }

    private PilotType AnalyzeMatchStmt(
        PilotParser.Match_stmtContext ctx,
        PilotType? expectedType,
        PilotSourceSpan? expectedOrigin,
        List<PilotType>? returnTypes)
    {
        bool isSubjectlessMatcher = ctx.test() == null;
        PilotType? expectedArmType = expectedType;
        if (isSubjectlessMatcher && expectedType?.Kind == PilotTypeKind.Function)
        {
            expectedArmType = expectedType.ReturnType;
        }

        PilotType scrutineeType = ctx.test() != null
            ? Synthesize(ctx.test())
            : (expectedType?.Kind == PilotTypeKind.Function && expectedType.TypeArguments.Count > 0
                ? expectedType.TypeArguments[0]
                : PilotType.Any);
        string? scrutineeVar = ctx.test() != null && IsSimpleIdentifier(ctx.test().GetText().Trim())
            ? ctx.test().GetText().Trim()
            : null;

        var arms = ctx.match_suite()?.match_arm();
        if (arms == null || arms.Length == 0) return PilotType.Void;

        var armTypes = new List<PilotType>();
        var survivingFlows = new List<Dictionary<string, PilotType>>();
        PilotType remainingScrutineeType = scrutineeType;

        foreach (var arm in arms)
        {
            _engine.PushScope();
            PushFlowScope();

            if (arm.pattern() != null)
            {
                BindMatchPatternVariables(arm.pattern(), remainingScrutineeType, arm.Start?.Line);
                if (scrutineeVar != null && TryExtractPatternNarrowedType(arm.pattern(), remainingScrutineeType, out var armNarrowed))
                {
                    SetFlowNarrowedType(scrutineeVar, armNarrowed, arm.suite()?.Start?.Line ?? arm.Start.Line);
                    if (arm.test() == null)
                    {
                        remainingScrutineeType = remainingScrutineeType.SubtractType(armNarrowed);
                    }
                }
            }

            if (arm.test() != null)
            {
                var (trueN, _, _) = ExtractConditionNarrowing(arm.test());
                foreach (var kvp in trueN)
                    SetFlowNarrowedType(kvp.Key, kvp.Value, arm.suite()?.Start?.Line ?? arm.Start.Line);
            }

            if (arm.suite() != null)
            {
                PilotType armType = expectedArmType != null && expectedOrigin != null
                    ? CheckSuite(arm.suite(), expectedArmType, expectedOrigin)
                    : AnalyzeSuiteForReturn(arm.suite(), returnTypes ?? new List<PilotType>());
                armTypes.Add(armType);

                var endFlow = PopFlowScope();
                _engine.PopScope();
                if (!SuiteAlwaysExits(arm.suite()))
                    survivingFlows.Add(endFlow);
            }
            else
            {
                PopFlowScope();
                _engine.PopScope();
            }
        }

        if (survivingFlows.Count > 0)
        {
            int afterLine = (ctx.Stop?.Line ?? ctx.Start.Line) + 1;
            var allKeys = survivingFlows.SelectMany(d => d.Keys).Distinct(StringComparer.Ordinal).ToList();
            foreach (var key in allKeys)
            {
                var types = survivingFlows
                    .Where(f => f.ContainsKey(key))
                    .Select(f => f[key])
                    .ToList();
                if (types.Count > 0)
                    SetFlowNarrowedType(key, JoinTypes(types), afterLine);
            }
        }

        var nonVoidArms = armTypes.Where(t => t != PilotType.Void && t != PilotType.Any).ToList();
        var joinedResult = nonVoidArms.Count > 0 ? JoinTypes(nonVoidArms) : (armTypes.Count > 0 ? armTypes[0] : PilotType.Void);
        if (isSubjectlessMatcher && expectedArmType?.Kind == PilotTypeKind.TypeVariable)
        {
            expectedArmType.Unify(joinedResult, _engine.Substitutions);
        }
        var result = isSubjectlessMatcher
            ? PilotType.FunctionOf(new[] { scrutineeType }, _engine.ResolveType(joinedResult))
            : joinedResult;
        _nodeTypes[ctx] = result;
        return result;
    }

    private PilotType AnalyzeForStmt(
        PilotParser.For_stmtContext ctx,
        PilotType? expectedType,
        PilotSourceSpan? expectedOrigin,
        List<PilotType>? returnTypes)
    {
        var forTests = ctx.test();
        var iterType = forTests != null && forTests.Length > 0 ? Synthesize(forTests[0]) : PilotType.Any;
        PilotType elemType = PilotType.Int;
        if (iterType.Kind == PilotTypeKind.Collection && iterType.TypeArguments.Count > 0)
            elemType = iterType.TypeArguments[0];
        else if (iterType == PilotType.String)
            elemType = PilotType.String;

        _engine.PushScope();
        PushFlowScope();

        string? loopVar = ctx.for_target()?.binding_pattern()?.FirstOrDefault()?.identifier()?.GetText()
            ?? ctx.for_target()?.exprlist()?.test()?.FirstOrDefault()?.GetText();
        if (!string.IsNullOrEmpty(loopVar))
        {
            _engine.SetVariableType(loopVar, elemType);
            SetFlowNarrowedType(loopVar, elemType, ctx.Start?.Line);
        }

        var suites = ctx.suite();
        var loopYieldOrBreakTypes = new List<PilotType>();
        PilotType? expectedElem = null;
        if (expectedType?.Kind == PilotTypeKind.Collection && expectedType.TypeArguments.Count > 0)
            expectedElem = expectedType.TypeArguments[0];

        if (suites != null && suites.Length > 0)
        {
            _loopFlowContextStack.Push((loopYieldOrBreakTypes, expectedElem ?? expectedType, expectedOrigin));
            try
            {
                AnalyzeSuiteForReturn(suites[0], returnTypes ?? new List<PilotType>());
            }
            finally
            {
                _loopFlowContextStack.Pop();
            }

            if (loopYieldOrBreakTypes.Count == 0)
            {
                CollectLoopBodyFlowTypes(suites[0], loopYieldOrBreakTypes, expectedElem ?? expectedType, expectedOrigin);
            }
        }

        PopFlowScope();
        _engine.PopScope();

        PilotType? thenType = null;
        if (suites != null && suites.Length > 1)
        {
            _engine.PushScope();
            PushFlowScope();
            thenType = expectedType != null && expectedOrigin != null
                ? CheckSuite(suites[1], expectedType, expectedOrigin)
                : AnalyzeSuiteForReturn(suites[1], returnTypes ?? new List<PilotType>());
            PopFlowScope();
            _engine.PopScope();
        }

        PilotType resultType = PilotType.Void;
        if (_loopAnalyzer.LoopInfos.TryGetValue(ctx, out var info))
        {
            if (info.ReturnMode == LoopReturnMode.CollectionYield)
            {
                var yieldedElem = loopYieldOrBreakTypes.Count > 0
                    ? JoinTypes(loopYieldOrBreakTypes)
                    : (expectedElem ?? PilotType.Any);
                if (expectedType?.Kind == PilotTypeKind.Collection &&
                    (string.Equals(expectedType.Name, "SliceBuffer", StringComparison.OrdinalIgnoreCase) ||
                     string.Equals(expectedType.Name, "SharedBuffer", StringComparison.OrdinalIgnoreCase)))
                {
                    resultType = new PilotType(PilotTypeKind.Collection, expectedType.Name, new[] { yieldedElem });
                }
                else
                {
                    resultType = PilotType.ListOf(yieldedElem);
                }
            }
            else if (info.ReturnMode == LoopReturnMode.ScalarBreak)
            {
                if (thenType != null)
                    loopYieldOrBreakTypes.Add(thenType);
                resultType = loopYieldOrBreakTypes.Count > 0
                    ? JoinTypes(loopYieldOrBreakTypes)
                    : (expectedType ?? PilotType.Any);
            }
        }

        _nodeTypes[ctx] = resultType;
        return resultType;
    }

    private void CollectLoopBodyFlowTypes(
        IParseTree node,
        List<PilotType> collected,
        PilotType? expectedFlowType,
        PilotSourceSpan? expectedOrigin)
    {
        if (node is PilotParser.For_stmtContext)
            return;

        if (node is PilotParser.Flow_stmtContext flow)
        {
            if (flow.YIELD() != null && flow.testlist()?.test() is { Length: > 0 } yTests)
            {
                var t = expectedFlowType != null && expectedOrigin != null
                    ? Check(yTests[0], expectedFlowType, expectedOrigin)
                    : Synthesize(yTests[0]);
                collected.Add(t);
            }
            else if (flow.BREAK() != null && flow.test() is { Length: > 0 } bTests)
            {
                var t = expectedFlowType != null && expectedOrigin != null
                    ? Check(bTests[0], expectedFlowType, expectedOrigin)
                    : Synthesize(bTests[0]);
                collected.Add(t);
            }
            return;
        }

        for (int i = 0; i < node.ChildCount; i++)
        {
            CollectLoopBodyFlowTypes(node.GetChild(i), collected, expectedFlowType, expectedOrigin);
        }
    }

    private PilotType AnalyzeFlowStmt(PilotParser.Flow_stmtContext ctx, List<PilotType>? returnTypes)
    {
        if (ctx.RETURN() != null)
        {
            var tests = ctx.testlist()?.test();
            if (tests == null || tests.Length == 0)
            {
                returnTypes?.Add(PilotType.Void);
                return PilotType.Void;
            }

            var expectedRet = _expectedReturnStack.Count > 0 ? _expectedReturnStack.Peek() : null;
            PilotType retValType;
            if (tests.Length == 1)
            {
                if (TryExtractFailArgumentType(tests[0], out var failErrType, out string? failErrName))
                {
                    if (_activeSchemeStack.Count > 0 && _activeSchemeStack.Peek() is { } scheme && !string.IsNullOrEmpty(failErrName))
                    {
                        scheme.InferredErrorVariants.Add(failErrName);
                    }
                    retValType = expectedRet != null && expectedRet.IsResult
                        ? expectedRet
                        : PilotType.ResultOf(PilotType.NewTypeVariable("Ok"), failErrType);
                }
                else if (expectedRet != null && expectedRet.Kind != PilotTypeKind.Any && expectedRet.Kind != PilotTypeKind.TypeVariable)
                {
                    var targetRet = expectedRet.IsResult ? expectedRet.TypeArguments[0] : expectedRet;
                    var origin = PilotSourceSpan.FromContext(ctx, "enclosing function return signature");
                    retValType = Check(tests[0], targetRet, origin);
                }
                else
                {
                    retValType = Synthesize(tests[0]);
                }
            }
            else
            {
                retValType = PilotType.TupleOf(tests.Select(Synthesize).ToArray());
            }

            returnTypes?.Add(retValType);
            return retValType;
        }

        if (ctx.YIELD() != null && ctx.testlist()?.test() is { Length: > 0 } yTests)
        {
            PilotType yType;
            if (_loopFlowContextStack.Count > 0 && _loopFlowContextStack.Peek() is { ExpectedType: not null, ExpectedOrigin: not null } loopExp)
            {
                yType = Check(yTests[0], loopExp.ExpectedType, loopExp.ExpectedOrigin);
            }
            else
            {
                yType = Synthesize(yTests[0]);
            }
            if (_loopFlowContextStack.Count > 0)
            {
                _loopFlowContextStack.Peek().FlowTypes.Add(yType);
            }
            return yType;
        }

        if (ctx.BREAK() != null && ctx.test() is { Length: > 0 } bTests)
        {
            PilotType bType;
            if (_loopFlowContextStack.Count > 0 && _loopFlowContextStack.Peek() is { ExpectedType: not null, ExpectedOrigin: not null } loopExp)
            {
                bType = Check(bTests[0], loopExp.ExpectedType, loopExp.ExpectedOrigin);
            }
            else
            {
                bType = Synthesize(bTests[0]);
            }
            if (_loopFlowContextStack.Count > 0)
            {
                _loopFlowContextStack.Peek().FlowTypes.Add(bType);
            }
            return bType;
        }

        return PilotType.Void;
    }

    private PilotType AnalyzeExprStmt(PilotParser.Expr_stmtContext ctx)
    {
        var testlist = ctx.testlist();
        var rhsTests = ctx.test();
        if (testlist == null) return PilotType.Void;

        if (ctx.EQUAL().Length > 0 && rhsTests != null && rhsTests.Length > 0)
        {
            string lhsText = testlist.GetText().Trim();
            var rhsTest = rhsTests[^1];

            if (IsSimpleIdentifier(lhsText) && _engine.TryLookupType(lhsText, out var existingType) && existingType.Kind != PilotTypeKind.Any)
            {
                var origin = PilotSourceSpan.FromContext(testlist, $"variable '{lhsText}'");
                var rhsType = Check(rhsTest, existingType, origin);
                SetFlowNarrowedType(lhsText, rhsType, ctx.Start?.Line);
                return rhsType;
            }
            else
            {
                var rhsType = Synthesize(rhsTest);
                if (IsSimpleIdentifier(lhsText))
                {
                    _engine.SetVariableType(lhsText, rhsType);
                    SetFlowNarrowedType(lhsText, rhsType, ctx.Start?.Line);
                }
                return rhsType;
            }
        }

        var singleTests = testlist.test();
        if (singleTests != null && singleTests.Length > 0)
        {
            return Synthesize(singleTests[0]);
        }
        return PilotType.Void;
    }

