/// <summary>
/// Principal type scheme inferred for a Pilot function declaration, including
/// row-polymorphic parameter constraints, inferred return type, and inferred error sets.
/// </summary>
public sealed class PilotFunctionScheme
{
    public string Name { get; }
    public PilotParser.Func_defContext Context { get; }
    public List<string> ParameterNames { get; } = new();
    public List<PilotType> ParameterTypes { get; } = new();
    public List<bool> ParameterHasExplicitType { get; } = new();
    public PilotType ReturnType { get; set; } = PilotType.Any;
    public bool HasExplicitReturnType { get; set; }
    public bool HasOpenErrorMarker { get; set; }
    public HashSet<string> InferredErrorVariants { get; } = new(StringComparer.Ordinal);
    public Dictionary<int, Dictionary<string, PilotType>> RowParameterFields { get; } = new();

    public PilotFunctionScheme(string name, PilotParser.Func_defContext context)
    {
        Name = name;
        Context = context;
    }

    public PilotType BuildFunctionType(Dictionary<int, PilotType> substitutions)
    {
        var resolvedParams = new PilotType[ParameterTypes.Count];
        for (int i = 0; i < ParameterTypes.Count; i++)
        {
            if (RowParameterFields.TryGetValue(i, out var rowMap) && rowMap.Count > 0)
            {
                var resolvedRow = new Dictionary<string, PilotType>(StringComparer.Ordinal);
                foreach (var kvp in rowMap)
                {
                    resolvedRow[kvp.Key] = PilotType.Resolve(kvp.Value, substitutions);
                }
                resolvedParams[i] = PilotType.RowRecordOf(resolvedRow, isOpenRow: true, rowTailName: "R");
            }
            else
            {
                resolvedParams[i] = PilotType.Resolve(ParameterTypes[i], substitutions);
            }
        }

        var resolvedRet = PilotType.Resolve(ReturnType, substitutions);
        if (InferredErrorVariants.Count > 0 && !resolvedRet.IsResult)
        {
            var errTypes = InferredErrorVariants
                .OrderBy(e => e, StringComparer.Ordinal)
                .Select(PilotTypeInferenceEngine.ParseTypeString)
                .ToArray();
            var errUnion = PilotType.UnionOf(errTypes);
            resolvedRet = PilotType.ResultOf(resolvedRet, errUnion);
        }
        else if (HasOpenErrorMarker && resolvedRet.IsResult && resolvedRet.TypeArguments[1].Kind == PilotTypeKind.Any && InferredErrorVariants.Count > 0)
        {
            var errTypes = InferredErrorVariants
                .OrderBy(e => e, StringComparer.Ordinal)
                .Select(PilotTypeInferenceEngine.ParseTypeString)
                .ToArray();
            var errUnion = PilotType.UnionOf(errTypes);
            resolvedRet = PilotType.ResultOf(resolvedRet.TypeArguments[0], errUnion);
        }

        return PilotType.FunctionOf(resolvedParams, resolvedRet);
    }
}

/// <summary>
/// Nominal struct/record/class/ADT layout metadata used by bidirectional checking,
/// flow narrowing, typestate verification, and row-polymorphic call-site monomorphization.
/// </summary>
public sealed class PilotNominalTypeLayout
{
    public string Name { get; }
    public PilotType NominalType { get; }
    public List<(string Name, PilotType Type, int Offset)> OrderedFields { get; } = new();
    public Dictionary<string, (PilotType Type, int Offset)> FieldMap { get; } = new(StringComparer.Ordinal);
    public Dictionary<string, List<PilotType>> MethodOverloads { get; } = new(StringComparer.Ordinal);
    public List<string> States { get; } = new();
    public string? InitialState => States.Count > 0 ? States[0] : null;
    public Dictionary<string, string> MethodRequiredState { get; } = new(StringComparer.Ordinal);
    public Dictionary<(string State, string Method), string> StateTransitions { get; } = new();
    public string? ParentAdtName { get; set; }
    public List<string> AdtVariants { get; } = new();

    public PilotNominalTypeLayout(string name, PilotType nominalType)
    {
        Name = name;
        NominalType = nominalType;
    }

    public void AddField(string fieldName, PilotType fieldType)
    {
        if (FieldMap.ContainsKey(fieldName)) return;
        int offset = OrderedFields.Count;
        OrderedFields.Add((fieldName, fieldType, offset));
        FieldMap[fieldName] = (fieldType, offset);
    }
}

/// <summary>
/// Full Bidirectional + Hindley-Milner + Dominator Control-Flow Narrowing + Row-Polymorphic
/// Type Inference Engine for Milestone 16 (16.1–16.4).
/// </summary>
public sealed class PilotBidirectionalInferencer
{
    private readonly PilotTypeInferenceEngine _engine;
    private readonly Dictionary<string, PilotNominalTypeLayout> _nominalLayouts = new(StringComparer.Ordinal);
    private readonly Dictionary<string, List<PilotFunctionScheme>> _functionGroups = new(StringComparer.Ordinal);
    private readonly Dictionary<PilotParser.Func_defContext, PilotFunctionScheme> _schemesByNode = new();
    private readonly List<PilotTypeConstraint> _constraints = new();
    private readonly List<PilotMonomorphizedCallSite> _monomorphizedCallSites = new();
    private readonly List<PilotInlayHint> _inlayHints = new();
    private readonly Dictionary<ParserRuleContext, PilotType> _nodeTypes = new();
    private readonly Dictionary<(int Line, string Name), PilotType> _lineFlowTypes = new();
    private readonly Stack<Dictionary<string, PilotType>> _flowNarrowingStack = new();
    private readonly Stack<PilotType?> _expectedReturnStack = new();
    private readonly Stack<PilotFunctionScheme?> _activeSchemeStack = new();
    private readonly Stack<(List<PilotType> FlowTypes, PilotType? ExpectedType, PilotSourceSpan? ExpectedOrigin)> _loopFlowContextStack = new();
    private readonly PilotForLoopAnalyzer _loopAnalyzer = new();
    private readonly HashSet<string> _externFunctionNames = new(StringComparer.Ordinal);
    private readonly HashSet<string> _mutableVariableNames = new(StringComparer.Ordinal);
    private bool _suppressDiagnostics;

    public IReadOnlyDictionary<string, PilotNominalTypeLayout> NominalLayouts => _nominalLayouts;
    public IReadOnlyDictionary<string, List<PilotFunctionScheme>> FunctionGroups => _functionGroups;
    public IReadOnlyList<PilotTypeConstraint> Constraints => _constraints;
    public IReadOnlyList<PilotMonomorphizedCallSite> MonomorphizedCallSites => _monomorphizedCallSites;
    public IReadOnlyList<PilotInlayHint> InlayHints => _inlayHints;
    public IReadOnlyDictionary<ParserRuleContext, PilotType> NodeTypes => _nodeTypes;

    public PilotBidirectionalInferencer(PilotTypeInferenceEngine engine)
    {
        _engine = engine;
        _flowNarrowingStack.Push(new Dictionary<string, PilotType>(StringComparer.Ordinal));
    }

    public PilotType? GetNarrowedTypeAt(ParserRuleContext node) =>
        _nodeTypes.TryGetValue(node, out var t) ? _engine.ResolveType(t) : null;

    public PilotType? GetFlowTypeAtLine(int oneBasedLine, string variableName) =>
        _lineFlowTypes.TryGetValue((oneBasedLine, variableName), out var t) ? _engine.ResolveType(t) : null;

    #region Entry Point & Pass Orchestration

    public void AnalyzeProgram(PilotParser.ProgramContext program)
    {
        _loopAnalyzer.CheckProgram(program);

        // Pass 1: Prescan nominal types (structs, records, classes + typestates, enums, ADTs) and function stubs
        PrescanProgramDeclarations(program);

        // Pass 2: Solve recursive & mutually recursive function SCCs via Tarjan fixed-point unification
        SolveFunctionSccs(program);

        // Pass 3: Full top-level bidirectional walk with dominator flow-sensitive narrowing
        var stmts = program.stmt();
        if (stmts != null)
        {
            foreach (var stmt in stmts)
            {
                if (stmt.compound_stmt()?.func_def() != null)
                    continue;
                AnalyzeStatement(stmt);
            }

            foreach (var stmt in stmts)
            {
                if (stmt.compound_stmt()?.func_def() is { } fnDef)
                {
                    AnalyzeFunctionBodyFinal(fnDef);
                }
            }
        }
    }

    #endregion

    #region Pass 1: Nominal Types, Typestates, ADTs & Function Stubs

    private void PrescanProgramDeclarations(IParseTree node)
    {
        switch (node)
        {
            case PilotParser.Struct_defContext structDef:
                RegisterStructLayout(structDef);
                break;
            case PilotParser.Record_defContext recDef:
                RegisterRecordLayout(recDef);
                break;
            case PilotParser.Class_defContext classDef:
                RegisterClassLayout(classDef);
                break;
            case PilotParser.Type_alias_stmtContext aliasDef:
                RegisterTypeAliasLayout(aliasDef);
                break;
            case PilotParser.Enum_defContext enumDef:
                RegisterEnumLayout(enumDef);
                break;
            case PilotParser.Func_defContext funcDef:
                if (!IsInsideClassOrState(funcDef))
                {
                    RegisterFunctionStub(funcDef);
                }
                return;
            case PilotParser.Extern_defContext externDef:
                if (externDef.extern_member() != null)
                {
                    foreach (var m in externDef.extern_member())
                    {
                        if ((m.DEF() != null || m.FN() != null) && m.identifier() != null)
                        {
                            string fnName = m.identifier().GetText();
                            if (m.suite() == null)
                            {
                                _externFunctionNames.Add(fnName);
                            }
                            var pTypes = new List<PilotType>();
                            if (m.parameters()?.parameter() != null)
                            {
                                foreach (var p in m.parameters().parameter())
                                {
                                    pTypes.Add(p.type_annotation()?.type_spec() != null
                                        ? PilotTypeInferenceEngine.ParseTypeString(p.type_annotation().type_spec().GetText())
                                        : PilotType.Any);
                                }
                            }
                            var retType = m.type_spec() != null
                                ? PilotTypeInferenceEngine.ParseTypeString(m.type_spec().GetText())
                                : PilotType.Any;
                            _engine.SetVariableType(fnName, PilotType.FunctionOf(pTypes, retType));
                        }
                    }
                }
                return;
        }

        for (int i = 0; i < node.ChildCount; i++)
        {
            PrescanProgramDeclarations(node.GetChild(i));
        }
    }

    private static bool IsInsideClassOrState(RuleContext ctx)
    {
        for (var p = ctx.Parent; p != null; p = p.Parent)
        {
            if (p is PilotParser.Class_defContext or PilotParser.State_defContext or PilotParser.Struct_defContext or PilotParser.Record_defContext)
                return true;
        }
        return false;
    }

    private void RegisterStructLayout(PilotParser.Struct_defContext ctx)
    {
        string name = ctx.identifier().GetText();
        bool isResource = HasResourceOrLinearDecorator(ctx.decorators());
        var nomType = isResource ? PilotType.ResourceOf(name) : new PilotType(PilotTypeKind.Primitive, name);
        var layout = new PilotNominalTypeLayout(name, nomType);

        if (ctx.struct_member() is { } members)
        {
            foreach (var m in members)
            {
                string fName = m.identifier().GetText();
                var fType = m.type_annotation()?.type_spec() is { } ts
                    ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                    : (m.test() != null ? Synthesize(m.test()) : PilotType.Any);
                layout.AddField(fName, fType);
                _engine.SetVariableType($"{name}.{fName}", fType);
            }
        }
        if (ctx.suite()?.stmt() is { } stmts)
        {
            ExtractSuiteFields(name, layout, stmts);
        }

        _nominalLayouts[name] = layout;
        var ctorType = PilotType.FunctionOf(layout.OrderedFields.Select(f => f.Type).ToArray(), nomType);
        _engine.SetVariableType(name, ctorType);
    }

    private void ExtractSuiteFields(string typeName, PilotNominalTypeLayout layout, PilotParser.StmtContext[] stmts)
    {
        foreach (var st in stmts)
        {
            if (st.simple_stmt()?.small_stmt() is { } smalls)
            {
                foreach (var sm in smalls)
                {
                    if (sm.annassign_stmt() is { } ann)
                    {
                        var annTests = ann.test();
                        string fName = annTests != null && annTests.Length > 0 ? annTests[0].GetText().Trim() : "";
                        var fType = PilotTypeInferenceEngine.ParseTypeString(ann.type_spec().GetText());
                        if (!string.IsNullOrEmpty(fName))
                        {
                            layout.AddField(fName, fType);
                            _engine.SetVariableType($"{typeName}.{fName}", fType);
                        }
                    }
                    else if (sm.let_stmt() is { } ls && ls.binding_pattern()?.identifier() is { } lid)
                    {
                        string fName = lid.GetText();
                        var fType = ls.type_annotation()?.type_spec() is { } ts
                            ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                            : (ls.test() != null ? Synthesize(ls.test()) : PilotType.Any);
                        layout.AddField(fName, fType);
                        _engine.SetVariableType($"{typeName}.{fName}", fType);
                    }
                    else if (sm.var_stmt() is { } vs && vs.binding_pattern()?.identifier() is { } vid)
                    {
                        string fName = vid.GetText();
                        var fType = vs.type_annotation()?.type_spec() is { } ts
                            ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                            : (vs.test() != null ? Synthesize(vs.test()) : PilotType.Any);
                        layout.AddField(fName, fType);
                        _engine.SetVariableType($"{typeName}.{fName}", fType);
                    }
                }
            }
        }
    }

    private void RegisterRecordLayout(PilotParser.Record_defContext ctx)
    {
        string name = ctx.identifier().GetText();
        var nomType = new PilotType(PilotTypeKind.Primitive, name);
        var layout = new PilotNominalTypeLayout(name, nomType);

        if (ctx.adt_field_list()?.adt_field() is { } adtFields)
        {
            for (int i = 0; i < adtFields.Length; i++)
            {
                string fName = adtFields[i].identifier()?.GetText() ?? $"Item{i + 1}";
                var fType = PilotTypeInferenceEngine.ParseTypeString(adtFields[i].type_spec().GetText());
                layout.AddField(fName, fType);
                _engine.SetVariableType($"{name}.{fName}", fType);
            }
        }
        if (ctx.struct_member() is { } structMembers)
        {
            foreach (var m in structMembers)
            {
                string fName = m.identifier().GetText();
                var fType = m.type_annotation()?.type_spec() is { } ts
                    ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                    : PilotType.Any;
                layout.AddField(fName, fType);
                _engine.SetVariableType($"{name}.{fName}", fType);
            }
        }

        _nominalLayouts[name] = layout;
        var ctorType = PilotType.FunctionOf(layout.OrderedFields.Select(f => f.Type).ToArray(), nomType);
        _engine.SetVariableType(name, ctorType);
    }

    private void RegisterClassLayout(PilotParser.Class_defContext ctx)
    {
        string name = ctx.identifier().GetText();
        bool isResource = HasResourceOrLinearDecorator(ctx.decorators());
        var nomType = isResource ? PilotType.ResourceOf(name) : new PilotType(PilotTypeKind.Primitive, name);
        var layout = new PilotNominalTypeLayout(name, nomType);

        if (ctx.suite()?.stmt() is { } stmts)
        {
            ExtractSuiteFields(name, layout, stmts);

            foreach (var st in stmts)
            {
                if (st.compound_stmt()?.func_def() is { } methodDef)
                {
                    RegisterClassMethod(layout, methodDef, requiredState: null);
                }
                else if (st.compound_stmt()?.state_def() is { } stateDef)
                {
                    string stateName = stateDef.identifier().GetText();
                    if (!layout.States.Contains(stateName, StringComparer.Ordinal))
                        layout.States.Add(stateName);

                    if (stateDef.suite()?.stmt() is { } stateStmts)
                    {
                        foreach (var sst in stateStmts)
                        {
                            if (sst.compound_stmt()?.func_def() is { } sMethod)
                            {
                                RegisterClassMethod(layout, sMethod, requiredState: stateName);
                            }
                        }
                    }
                }
            }
        }

        _nominalLayouts[name] = layout;
        var constructedType = layout.InitialState != null
            ? PilotType.WithTypestate(nomType, layout.InitialState)
            : nomType;
        var ctorType = PilotType.FunctionOf(layout.OrderedFields.Select(f => f.Type).ToArray(), constructedType);
        _engine.SetVariableType(name, ctorType);
    }

    private void RegisterClassMethod(PilotNominalTypeLayout layout, PilotParser.Func_defContext methodDef, string? requiredState)
    {
        string mName = methodDef.identifier().GetText();
        var paramTypes = new List<PilotType>();
        var parameters = methodDef.parameters()?.parameter();
        if (parameters != null)
        {
            foreach (var p in parameters)
            {
                string pName = p.identifier()?.GetText() ?? "arg";
                if (pName == "self") continue;
                var pType = p.type_annotation()?.type_spec() is { } ts
                    ? PilotTypeInferenceEngine.ParseTypeString(ts.GetText())
                    : PilotType.Any;
                paramTypes.Add(pType);
            }
        }

        PilotType retType = methodDef.type_spec() != null
            ? PilotTypeInferenceEngine.ParseTypeString(methodDef.type_spec().GetText())
            : InferSimpleSuiteReturnType(methodDef.suite());

        string? transitionTarget = FindTransitionTarget(methodDef);
        if (requiredState != null)
        {
            layout.MethodRequiredState[mName] = requiredState;
            if (!string.IsNullOrEmpty(transitionTarget))
            {
                layout.StateTransitions[(requiredState, mName)] = transitionTarget;
                if (retType.Name.Equals(layout.Name, StringComparison.OrdinalIgnoreCase) || retType == PilotType.Any)
                {
                    retType = PilotType.WithTypestate(layout.NominalType, transitionTarget);
                }
            }
        }
        else if (!string.IsNullOrEmpty(transitionTarget))
        {
            foreach (var st in layout.States)
            {
                layout.StateTransitions[(st, mName)] = transitionTarget;
            }
        }

        var fnType = PilotType.FunctionOf(paramTypes, retType);
        if (!layout.MethodOverloads.TryGetValue(mName, out var overloads))
        {
            overloads = new List<PilotType>();
            layout.MethodOverloads[mName] = overloads;
        }
        overloads.Add(fnType);
        _engine.SetVariableType($"{layout.Name}.{mName}", fnType);
    }

    private static string? FindTransitionTarget(PilotParser.Func_defContext methodDef)
    {
        if (methodDef.type_spec() is { } ts)
        {
            string txt = ts.GetText();
            int bracketOpen = txt.IndexOfAny(new[] { '[', '<' });
            int bracketClose = txt.LastIndexOfAny(new[] { ']', '>' });
            if (bracketOpen > 0 && bracketClose > bracketOpen + 1)
            {
                return txt[(bracketOpen + 1)..bracketClose].Trim();
            }
        }

        string bodyText = methodDef.suite()?.GetText() ?? "";
        const string marker = "transition_to(";
        int idx = bodyText.IndexOf(marker, StringComparison.Ordinal);
        if (idx >= 0)
        {
            int start = idx + marker.Length;
            int end = bodyText.IndexOf(')', start);
            if (end > start)
            {
                string arg = bodyText[start..end].Trim().Trim('"', '\'', ':');
                if (!string.IsNullOrEmpty(arg))
                    return arg;
            }
        }
        return null;
    }

    private void RegisterTypeAliasLayout(PilotParser.Type_alias_stmtContext ctx)
    {
        string name = ctx.identifier().GetText();
        if (ctx.adt_sum_body() is { } sumBody)
        {
            var adtType = new PilotType(PilotTypeKind.Primitive, name);
            var adtLayout = new PilotNominalTypeLayout(name, adtType);
            _nominalLayouts[name] = adtLayout;
            _engine.SetVariableType(name, adtType);

            for (int i = 0; i < sumBody.ChildCount; i++)
            {
                var ch = sumBody.GetChild(i);
                if (ch is PilotParser.IdentifierContext unitId)
                {
                    string vName = unitId.GetText();
                    adtLayout.AdtVariants.Add(vName);
                    RegisterVariantLayout(name, adtType, vName, null, null);
                }
                else if (ch is PilotParser.Adt_variantContext vc)
                {
                    string vName = vc.identifier().GetText();
                    adtLayout.AdtVariants.Add(vName);
                    RegisterVariantLayout(name, adtType, vName, vc.adt_field_list(), vc.struct_member());
                }
                else if (ch is PilotParser.Adt_variant_payloadContext vpc)
                {
                    string vName = vpc.identifier().GetText();
                    adtLayout.AdtVariants.Add(vName);
                    RegisterVariantLayout(name, adtType, vName, vpc.adt_field_list(), vpc.struct_member());
                }
            }
        }
        else if (ctx.type_spec() != null)
        {
            var aliased = PilotTypeInferenceEngine.ParseTypeString(ctx.type_spec().GetText());
            _engine.SetVariableType(name, aliased);
        }
    }

    private void RegisterEnumLayout(PilotParser.Enum_defContext ctx)
    {
        string name = ctx.identifier().GetText();
        var enumType = new PilotType(PilotTypeKind.Primitive, name);
        var enumLayout = new PilotNominalTypeLayout(name, enumType);
        _nominalLayouts[name] = enumLayout;
        _engine.SetVariableType(name, enumType);

        if (ctx.enum_suite()?.enum_member() is { } members)
        {
            foreach (var m in members)
            {
                string vName = m.identifier().GetText();
                enumLayout.AdtVariants.Add(vName);
                RegisterVariantLayout(name, enumType, vName, m.adt_field_list(), m.struct_member());
            }
        }
    }

    private void RegisterVariantLayout(
        string adtName,
        PilotType adtType,
        string variantName,
        PilotParser.Adt_field_listContext? fieldList,
        PilotParser.Struct_memberContext[]? structMembers)
    {
        var vType = new PilotType(PilotTypeKind.Primitive, variantName);
        var vLayout = new PilotNominalTypeLayout(variantName, vType)
        {
            ParentAdtName = adtName
        };

        if (fieldList?.adt_field() is { } fields)
        {
            for (int i = 0; i < fields.Length; i++)
            {
                string fName = fields[i].identifier()?.GetText() ?? $"Item{i + 1}";
                var fType = PilotTypeInferenceEngine.ParseTypeString(fields[i].type_spec().GetText());
                vLayout.AddField(fName, fType);
                _engine.SetVariableType($"{variantName}.{fName}", fType);
            }
        }
        else if (structMembers != null)
        {
            foreach (var sm in structMembers)
            {
                string fName = sm.identifier().GetText();
                var fType = PilotTypeInferenceEngine.ParseTypeString(sm.type_annotation()?.type_spec()?.GetText() ?? "any");
                vLayout.AddField(fName, fType);
                _engine.SetVariableType($"{variantName}.{fName}", fType);
            }
        }

        _nominalLayouts[variantName] = vLayout;
        if (vLayout.OrderedFields.Count == 0)
        {
            _engine.SetVariableType(variantName, adtType);
            _engine.SetVariableType($"{adtName}.{variantName}", adtType);
        }
        else
        {
            var ctor = PilotType.FunctionOf(vLayout.OrderedFields.Select(f => f.Type).ToArray(), adtType);
            _engine.SetVariableType(variantName, ctor);
            _engine.SetVariableType($"{adtName}.{variantName}", ctor);
        }
    }

    private static bool HasResourceOrLinearDecorator(PilotParser.DecoratorsContext? decs)
    {
        if (decs?.decorator() == null) return false;
        foreach (var d in decs.decorator())
        {
            string name = d.dotted_name()?.GetText() ?? "";
            if (name is "resource" or "linear")
                return true;
        }
        return false;
    }

    private void RegisterFunctionStub(PilotParser.Func_defContext ctx)
    {
        string name = ctx.identifier().GetText();
        var scheme = new PilotFunctionScheme(name, ctx);

        var parameters = ctx.parameters()?.parameter();
        if (parameters != null)
        {
            foreach (var p in parameters)
            {
                string pName = p.identifier()?.GetText() ?? "arg";
                string pTypeStr = p.type_annotation()?.type_spec()?.GetText() ?? "";
                bool hasExplicit = !string.IsNullOrEmpty(pTypeStr);
                PilotType pType = hasExplicit
                    ? PilotTypeInferenceEngine.ParseTypeString(pTypeStr)
                    : PilotType.NewTypeVariable("T");
                scheme.ParameterNames.Add(pName);
                scheme.ParameterTypes.Add(pType);
                scheme.ParameterHasExplicitType.Add(hasExplicit);
            }
        }

        string declaredRetStr = ctx.type_spec()?.GetText() ?? "";
        if (!string.IsNullOrEmpty(declaredRetStr))
        {
            scheme.HasExplicitReturnType = true;
            scheme.ReturnType = PilotTypeInferenceEngine.ParseTypeString(declaredRetStr);
            if (scheme.ReturnType.IsResult && scheme.ReturnType.TypeArguments[1].Kind == PilotTypeKind.Any)
            {
                scheme.HasOpenErrorMarker = true;
            }
        }
        else
        {
            scheme.HasExplicitReturnType = false;
            scheme.ReturnType = PilotType.NewTypeVariable("R");
        }

        _schemesByNode[ctx] = scheme;
        if (!_functionGroups.TryGetValue(name, out var list))
        {
            list = new List<PilotFunctionScheme>();
            _functionGroups[name] = list;
        }
        list.Add(scheme);
        _engine.SetVariableType(name, scheme.BuildFunctionType(_engine.Substitutions));
    }

