/// <summary>
/// Source span and provenance description for a type inference constraint or synthesized type.
/// </summary>
public sealed class PilotSourceSpan
{
    public int StartLine { get; }
    public int StartColumn { get; }
    public int EndLine { get; }
    public int EndColumn { get; }
    public string SourceText { get; }
    public string OriginDescription { get; }

    public PilotSourceSpan(
        int startLine,
        int startColumn,
        int endLine,
        int endColumn,
        string sourceText,
        string originDescription)
    {
        StartLine = startLine;
        StartColumn = startColumn;
        EndLine = endLine;
        EndColumn = endColumn;
        SourceText = sourceText;
        OriginDescription = originDescription;
    }

    public static PilotSourceSpan FromContext(ParserRuleContext? ctx, string originDescription)
    {
        if (ctx?.Start == null)
            return new PilotSourceSpan(1, 0, 1, 1, "", originDescription);

        int startLine = ctx.Start.Line;
        int startCol = ctx.Start.Column;
        int endLine = ctx.Stop?.Line ?? startLine;
        int endCol = ctx.Stop != null ? ctx.Stop.Column + (ctx.Stop.Text?.Length ?? 1) : startCol + 1;
        return new PilotSourceSpan(startLine, startCol, endLine, endCol, ctx.GetText(), originDescription);
    }

    public static PilotSourceSpan FromToken(IToken? token, string originDescription)
    {
        if (token == null)
            return new PilotSourceSpan(1, 0, 1, 1, "", originDescription);

        int len = token.Text?.Length ?? 1;
        return new PilotSourceSpan(token.Line, token.Column, token.Line, token.Column + len, token.Text ?? "", originDescription);
    }

    public override string ToString() => $"{OriginDescription} (line {StartLine}:{StartColumn})";
}

/// <summary>
/// Unification constraint with exact AST provenance spans for expected and actual types.
/// </summary>
public sealed class PilotTypeConstraint
{
    public string Code { get; }
    public PilotType ExpectedType { get; }
    public PilotType ActualType { get; }
    public PilotSourceSpan ExpectedProvenance { get; }
    public PilotSourceSpan ActualProvenance { get; }
    public bool IsSatisfied { get; }

    public PilotTypeConstraint(
        string code,
        PilotType expectedType,
        PilotType actualType,
        PilotSourceSpan expectedProvenance,
        PilotSourceSpan actualProvenance,
        bool isSatisfied)
    {
        Code = code;
        ExpectedType = expectedType;
        ActualType = actualType;
        ExpectedProvenance = expectedProvenance;
        ActualProvenance = actualProvenance;
        IsSatisfied = isSatisfied;
    }

    public string FormatDiagnosticMessage() =>
        $"Type mismatch: cannot unify '{ActualType}' (synthesized from {ActualProvenance.OriginDescription} at line {ActualProvenance.StartLine}:{ActualProvenance.StartColumn}) " +
        $"with expected type '{ExpectedType}' (required by {ExpectedProvenance.OriginDescription} at line {ExpectedProvenance.StartLine}:{ExpectedProvenance.StartColumn}).";
}

