namespace Pilot.Analysis.Comptime;

public enum PilotDemotedBindingKind
{
    LocalSlot,
    UpvalueSlot,
    ModuleSlot,
    ComptimeConstant,
    ContextDisplaySlot,
    DynamicScopeFallback
}

public sealed record PilotDemotedVariableCoordinate(
    string Name,
    PilotDemotedBindingKind Kind,
    int SlotIndex,
    int FrameDepthDelta = 0);

public sealed record PilotDemotedFieldAccess(
    string ReceiverType,
    string FieldName,
    int FieldSlotIndex,
    int ByteOffset,
    int Line);

public sealed record PilotDemotedProjectionPlan(
    string SourceType,
    string TargetType,
    IReadOnlyList<(string FieldName, int SourceSlot, int TargetSlot)> FieldMappings,
    string? StaticAdapterFunctionName,
    int Line);

public sealed record PilotFunctionAuditSummary(
    string FunctionName,
    bool IsZeroRuntime,
    bool IsHardRealtime,
    bool IsComptime,
    int DemotedLocals,
    int DemotedUpvalues,
    int DemotedFieldSlots,
    int DemotedDirectCalls,
    int DemotedProjections,
    int ErasedUnitsAndStates,
    int PrecomputedCallQuotes,
    int ElidedContracts,
    int DemotedContextSlots,
    int RemainingAstFallbacks,
    int RemainingDynamicLookups)
{
    public int LocalSlotCount => DemotedLocals;
    public int UpvalueCaptureCount => DemotedUpvalues;
    public int StaticFieldAccessCount => DemotedFieldSlots;
    public int StaticProjectionCount => DemotedProjections;
    public int ElidedContractCount => ElidedContracts;
    public int ContextSlotLoadCount => DemotedContextSlots;
    public int DynamicFallbackCount => RemainingDynamicLookups + RemainingAstFallbacks;
}

/// <summary>
/// Comprehensive report generated by <see cref="PilotStaticDemotionPass"/> for bytecode lowering,
/// canonical transpilation IR, and `pilot check --comptime-audit` verification (Milestone 19.1–19.3).
/// </summary>
public sealed class PilotStaticDemotionReport
{
    public Dictionary<IParseTree, PilotDemotedVariableCoordinate> VariableCoordinates { get; } = new(ReferenceEqualityComparer.Instance);
    public Dictionary<IParseTree, PilotDemotedFieldAccess> FieldAccesses { get; } = new(ReferenceEqualityComparer.Instance);
    public Dictionary<IParseTree, PilotDemotedProjectionPlan> ProjectionPlans { get; } = new(ReferenceEqualityComparer.Instance);
    public Dictionary<string, IReadOnlyList<string>> NominalFieldLayouts { get; } = new(StringComparer.Ordinal);
    public Dictionary<string, int> ContextSlotIds { get; } = new(StringComparer.Ordinal);
    public HashSet<IParseTree> ErasedUnitNodes { get; } = new(ReferenceEqualityComparer.Instance);
    public HashSet<IParseTree> VerifiedTypestateNodes { get; } = new(ReferenceEqualityComparer.Instance);
    public HashSet<IParseTree> PrecomputedCallQuoteNodes { get; } = new(ReferenceEqualityComparer.Instance);
    public HashSet<IParseTree> ElidedContractNodes { get; } = new(ReferenceEqualityComparer.Instance);
    public HashSet<string> FullyDischargedFunctions { get; } = new(StringComparer.Ordinal);
    public Dictionary<IParseTree, PilotValue> MaterializedComptimeValues { get; } = new(ReferenceEqualityComparer.Instance);
    public List<PilotFunctionAuditSummary> FunctionAudits { get; } = new();
    public Dictionary<string, PilotFunctionAuditSummary> FunctionSummaries { get; } = new(StringComparer.Ordinal);
    public List<PilotAnalysisDiagnostic> Diagnostics { get; } = new();

    public int ErasedUnitCount => ErasedUnitNodes.Count;

    public int TotalDemotedLocals { get; set; }
    public int TotalDemotedUpvalues { get; set; }
    public int TotalDemotedFieldSlots { get; set; }
    public int TotalDemotedDirectCalls { get; set; }
    public int TotalDemotedProjections { get; set; }
    public int TotalErasedUnitsAndStates { get; set; }
    public int TotalPrecomputedCallQuotes { get; set; }
    public int TotalElidedContracts { get; set; }
    public int TotalDemotedContextSlots { get; set; }
    public int TotalMaterializedRodataConstants => MaterializedComptimeValues.Count;
    public int TotalRemainingAstFallbacks { get; set; }
    public int TotalRemainingDynamicLookups { get; set; }

    public bool IsZeroRuntimeClean =>
        TotalRemainingAstFallbacks == 0 &&
        TotalRemainingDynamicLookups == 0 &&
        !Diagnostics.Exists(d => d.Code.StartsWith("COMPTIME", StringComparison.Ordinal) && d.IsError);
}

/// <summary>
/// Milestone 19.1–19.3 Compiler-Wide Runtime-to-Compile-Time Demotion &amp; `@zero_runtime` Audit Pass.
/// Coordinates across type inference, nominal layouts, contract verification, and `comptime` execution
/// to replace runtime string dictionaries and reflection with $O(1)$ static coordinates.
/// </summary>
public sealed class PilotStaticDemotionPass : PilotBaseVisitor<object?>
{
    private readonly PilotTypeInferenceEngine _typeEngine;
    private readonly PilotContractVerifier _contractVerifier;
    private readonly PilotComptimeEvaluator _comptimeEvaluator;
    private readonly PilotStaticDemotionReport _report = new();

    private sealed class LexicalFrame
    {
        public string Name { get; }
        public bool IsModuleRoot { get; }
        public bool IsZeroRuntime { get; }
        public bool IsHardRealtime { get; }
        public bool IsComptime { get; }
        public Dictionary<string, int> Slots { get; } = new(StringComparer.Ordinal);
        public HashSet<string> ContextualParams { get; } = new(StringComparer.Ordinal);
        public HashSet<string> DynamicVars { get; } = new(StringComparer.Ordinal);
        public Dictionary<string, string> LocalTypes { get; } = new(StringComparer.Ordinal);

        public int DemotedLocals { get; set; }
        public int DemotedUpvalues { get; set; }
        public int DemotedFieldSlots { get; set; }
        public int DemotedDirectCalls { get; set; }
        public int DemotedProjections { get; set; }
        public int ErasedUnitsAndStates { get; set; }
        public int PrecomputedCallQuotes { get; set; }
        public int ElidedContracts { get; set; }
        public int DemotedContextSlots { get; set; }
        public int RemainingAstFallbacks { get; set; }
        public int RemainingDynamicLookups { get; set; }

        public LexicalFrame(string name, bool isModuleRoot, bool isZeroRuntime, bool isHardRealtime, bool isComptime)
        {
            Name = name;
            IsModuleRoot = isModuleRoot;
            IsZeroRuntime = isZeroRuntime;
            IsHardRealtime = isHardRealtime;
            IsComptime = isComptime;
        }

        public int GetOrAllocateSlot(string name)
        {
            if (Slots.TryGetValue(name, out int slot)) return slot;
            slot = Slots.Count;
            Slots[name] = slot;
            return slot;
        }
    }

    private readonly List<LexicalFrame> _frames = new();
    private readonly HashSet<string> _knownFunctions = new(StringComparer.Ordinal);
    private readonly HashSet<string> _knownTypes = new(StringComparer.Ordinal);

    private LexicalFrame CurrentFrame => _frames[^1];

    public PilotStaticDemotionReport Report => _report;

    public PilotStaticDemotionPass(
        PilotTypeInferenceEngine typeEngine,
        PilotContractVerifier contractVerifier,
        PilotComptimeEvaluator comptimeEvaluator)
    {
        _typeEngine = typeEngine;
        _contractVerifier = contractVerifier;
        _comptimeEvaluator = comptimeEvaluator;
    }

    public static PilotStaticDemotionReport Analyze(
        PilotParser.ProgramContext program,
        PilotTypeInferenceEngine typeEngine,
        PilotContractVerifier contractVerifier,
        PilotComptimeEvaluator comptimeEvaluator)
    {
        var pass = new PilotStaticDemotionPass(typeEngine, contractVerifier, comptimeEvaluator);
        pass.Run(program);
        return pass.Report;
    }

    private void Run(PilotParser.ProgramContext program)
    {
        foreach (var (node, val) in _comptimeEvaluator.PrecomputedValues)
        {
            _report.MaterializedComptimeValues[node] = val;
        }
        _report.Diagnostics.AddRange(_comptimeEvaluator.Diagnostics);

        foreach (var node in _contractVerifier.DischargedNodes)
        {
            _report.ElidedContractNodes.Add(node);
            _report.TotalElidedContracts++;
        }
        foreach (var fn in _contractVerifier.DischargedFunctions)
        {
            _report.FullyDischargedFunctions.Add(fn);
        }

        PrescanNominalLayoutsAndDeclarations(program);

        bool moduleZeroRuntime = HasZeroRuntimePragmaOrDecorator(program);
        _frames.Add(new LexicalFrame("<module>", isModuleRoot: true, isZeroRuntime: moduleZeroRuntime, isHardRealtime: false, isComptime: false));
        VisitProgram(program);
        FinalizeFrame(_frames[^1]);
        _frames.RemoveAt(_frames.Count - 1);
    }

    private void PrescanNominalLayoutsAndDeclarations(PilotParser.ProgramContext program)
    {
        if (program?.stmt() == null) return;

        foreach (var stmt in program.stmt())
        {
            var comp = stmt.compound_stmt();
            if (comp == null) continue;

            if (comp.func_def() is { } fn)
            {
                string fnName = fn.identifier().GetText();
                _knownFunctions.Add(fnName);
            }
            else if (comp.record_def() is { } rec)
            {
                string name = rec.identifier().GetText();
                _knownTypes.Add(name);
                var fields = new List<string>();
                if (rec.adt_field_list()?.adt_field() != null)
                {
                    foreach (var p in rec.adt_field_list().adt_field())
                    {
                        if (p.identifier() != null) fields.Add(p.identifier().GetText());
                    }
                }
                if (rec.struct_member() != null)
                {
                    foreach (var sm in rec.struct_member())
                    {
                        if (sm.identifier() != null) fields.Add(sm.identifier().GetText());
                    }
                }
                _report.NominalFieldLayouts[name] = fields;
            }
            else if (comp.struct_def() is { } st)
            {
                string name = st.identifier().GetText();
                _knownTypes.Add(name);
                var fields = new List<string>();
                if (st.struct_member() != null)
                {
                    foreach (var sm in st.struct_member())
                    {
                        if (sm.identifier() != null) fields.Add(sm.identifier().GetText());
                    }
                }
                _report.NominalFieldLayouts[name] = fields;
            }
            else if (comp.class_def() is { } cls)
            {
                string name = cls.identifier().GetText();
                _knownTypes.Add(name);
                var fields = new List<string>();
                if (cls.suite()?.stmt() != null)
                {
                    foreach (var s in cls.suite().stmt())
                    {
                        var smalls = s.simple_stmt()?.small_stmt();
                        if (smalls == null) continue;
                        foreach (var sm in smalls)
                        {
                            string? fName = sm.let_stmt()?.binding_pattern()?.identifier()?.GetText()
                                         ?? sm.var_stmt()?.binding_pattern()?.identifier()?.GetText()
                                         ?? sm.annassign_stmt()?.test(0)?.GetText();
                            if (!string.IsNullOrEmpty(fName) && !fields.Contains(fName))
                            {
                                fields.Add(fName);
                            }
                        }
                    }
                }
                _report.NominalFieldLayouts[name] = fields;
            }
            else if (comp.enum_def() is { } en)
            {
                _knownTypes.Add(en.identifier().GetText());
            }
        }
    }

    public override object? VisitFunc_def(PilotParser.Func_defContext context)
    {
        string funcName = context.identifier().GetText();
        CurrentFrame.GetOrAllocateSlot(funcName);
        _knownFunctions.Add(funcName);

        GetDecoratorFlags(context.decorators(), out bool isZeroRt, out bool isHardRt);
        bool isComptime = context.COMPTIME() != null;

        var frame = new LexicalFrame(
            funcName,
            isModuleRoot: false,
            isZeroRuntime: isZeroRt || CurrentFrame.IsZeroRuntime,
            isHardRealtime: isHardRt || CurrentFrame.IsHardRealtime,
            isComptime: isComptime || CurrentFrame.IsComptime);

        var parameters = context.parameters()?.parameter();
        if (parameters != null)
        {
            foreach (var p in parameters)
            {
                string? pName = p.identifier()?.GetText();
                if (string.IsNullOrEmpty(pName)) continue;
                frame.GetOrAllocateSlot(pName);
                frame.DemotedLocals++;

                string? pType = p.type_annotation()?.type_spec()?.GetText();
                if (!string.IsNullOrEmpty(pType))
                {
                    frame.LocalTypes[pName] = pType;
                    if ((frame.IsZeroRuntime || frame.IsHardRealtime) &&
                        string.Equals(pType, "dynamic", StringComparison.OrdinalIgnoreCase))
                    {
                        _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                            "COMPTIME007",
                            $"Parameter '{pName}' in '@zero_runtime' / '@hard_realtime' function '{funcName}' cannot use boxed 'dynamic' type.",
                            p.Start.Line,
                            p.Start.Column,
                            isError: true));
                    }
                }

                if (p.CONTEXT() != null)
                {
                    frame.ContextualParams.Add(pName);
                    int ctxId = PilotExecutionContext.InternContextSlotId(pName);
                    _report.ContextSlotIds[pName] = ctxId;
                    frame.DemotedContextSlots++;
                    _report.TotalDemotedContextSlots++;
                }
            }
        }

        // Check design-by-contract clauses (19.1.6 / COMPTIME006)
        var clauses = context.contract_clause();
        if (clauses is { Length: > 0 })
        {
            if (_contractVerifier.IsFunctionContractFullyDischarged(funcName))
            {
                _report.ElidedContractNodes.Add(context);
                frame.ElidedContracts += clauses.Length;
                _report.TotalElidedContracts += clauses.Length;
            }
            else if (frame.IsZeroRuntime || frame.IsHardRealtime)
            {
                _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                    "COMPTIME006",
                    $"Function '{funcName}' is marked '@zero_runtime' / '@hard_realtime' but has contract clause(s) that could not be statically proven at all call sites.",
                    context.Start.Line,
                    context.Start.Column,
                    isError: true));
            }
        }

        _frames.Add(frame);
        if (context.suite() != null)
        {
            Visit(context.suite());
        }
        FinalizeFrame(frame);
        _frames.RemoveAt(_frames.Count - 1);
        return null;
    }

    public override object? VisitDynamic_stmt(PilotParser.Dynamic_stmtContext context)
    {
        string name = context.binding_pattern()?.identifier()?.GetText() ?? context.binding_pattern()?.GetText() ?? "_";
        CurrentFrame.DynamicVars.Add(name);
        CurrentFrame.RemainingDynamicLookups++;
        _report.TotalRemainingDynamicLookups++;

        if (CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime)
        {
            _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                "COMPTIME001",
                $"Dynamic binding 'dynamic {name}' is forbidden inside '@zero_runtime' / '@hard_realtime' scope '{CurrentFrame.Name}'.",
                context.Start.Line,
                context.Start.Column,
                isError: true));
        }

        return base.VisitDynamic_stmt(context);
    }

    public override object? VisitLet_stmt(PilotParser.Let_stmtContext context)
    {
        RegisterPatternDeclaration(context.binding_pattern(), context.type_annotation(), context.test(), context.Start.Line, context.Start.Column);
        return base.VisitLet_stmt(context);
    }

    public override object? VisitVar_stmt(PilotParser.Var_stmtContext context)
    {
        RegisterPatternDeclaration(context.binding_pattern(), context.type_annotation(), context.test(), context.Start.Line, context.Start.Column);
        return base.VisitVar_stmt(context);
    }

    public override object? VisitConst_stmt(PilotParser.Const_stmtContext context)
    {
        RegisterPatternDeclaration(context.binding_pattern(), context.type_annotation(), context.test(), context.Start.Line, context.Start.Column);
        return base.VisitConst_stmt(context);
    }

    private void RegisterPatternDeclaration(
        PilotParser.Binding_patternContext? pattern,
        PilotParser.Type_annotationContext? typeAnn,
        PilotParser.TestContext? initExpr,
        int line,
        int col)
    {
        if (pattern == null) return;
        string? explicitType = typeAnn?.type_spec()?.GetText();

        if ((CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime) &&
            string.Equals(explicitType, "dynamic", StringComparison.OrdinalIgnoreCase))
        {
            _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                "COMPTIME007",
                $"Variable '{pattern.GetText()}' in '@zero_runtime' / '@hard_realtime' scope '{CurrentFrame.Name}' cannot use boxed 'dynamic' type.",
                line,
                col,
                isError: true));
        }

        foreach (var id in ExtractPatternIdentifiers(pattern))
        {
            CurrentFrame.GetOrAllocateSlot(id);
            CurrentFrame.DemotedLocals++;
            _report.TotalDemotedLocals++;

            if (!string.IsNullOrEmpty(explicitType))
            {
                CurrentFrame.LocalTypes[id] = explicitType;
            }
            else if (initExpr != null && TryInferConstructedTypeName(initExpr, out string? inferredType))
            {
                CurrentFrame.LocalTypes[id] = inferredType!;
            }
            else if (_typeEngine.InferredTypes.TryGetValue(id, out var pt) && !string.IsNullOrEmpty(pt.Name) && pt.Name != "any")
            {
                CurrentFrame.LocalTypes[id] = pt.Name;
            }
        }
    }

    public override object? VisitWith_stmt(PilotParser.With_stmtContext context)
    {
        var items = context.with_item();
        if (items != null)
        {
            foreach (var item in items)
            {
                if (item.CONTEXT() != null && item.with_context_binding() != null)
                {
                    foreach (var cb in item.with_context_binding())
                    {
                        string key = cb.identifier().GetText();
                        int slotId = PilotExecutionContext.InternContextSlotId(key);
                        _report.ContextSlotIds[key] = slotId;
                        CurrentFrame.DemotedContextSlots++;
                        _report.TotalDemotedContextSlots++;
                    }
                }
            }
        }
        return base.VisitWith_stmt(context);
    }

    public override object? VisitTerm(PilotParser.TermContext context)
    {
        // Check DTO / Adapter projection `expr -> TargetType` (19.1.3)
        if (context.ARROW()?.Length > 0 && context.factor()?.Length >= 2)
        {
            var factors = context.factor();
            for (int i = 0; i < context.ARROW().Length && i + 1 < factors.Length; i++)
            {
                string targetType = factors[i + 1].GetText().Trim();
                string? sourceType = ResolveFactorStaticTypeName(factors[i]);

                if (!string.IsNullOrEmpty(sourceType) &&
                    _report.NominalFieldLayouts.TryGetValue(sourceType, out var srcFields) &&
                    _report.NominalFieldLayouts.TryGetValue(targetType, out var dstFields))
                {
                    var mappings = new List<(string FieldName, int SourceSlot, int TargetSlot)>();
                    for (int t = 0; t < dstFields.Count; t++)
                    {
                        int sIdx = IndexOfOrdinal(srcFields, dstFields[t]);
                        if (sIdx >= 0)
                        {
                            mappings.Add((dstFields[t], sIdx, t));
                        }
                    }
                    _report.ProjectionPlans[context] = new PilotDemotedProjectionPlan(
                        sourceType, targetType, mappings, null, context.Start.Line);
                    CurrentFrame.DemotedProjections++;
                    _report.TotalDemotedProjections++;
                }
                else if (CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime)
                {
                    _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                        "COMPTIME005",
                        $"Projection '-> {targetType}' in '@zero_runtime' scope '{CurrentFrame.Name}' requires statically known source and target layouts.",
                        context.Start.Line,
                        context.Start.Column,
                        isError: true));
                }
            }
        }

        return base.VisitTerm(context);
    }

    public override object? VisitAtom_expr(PilotParser.Atom_exprContext context)
    {
        var atom = context.atom();
        var trailers = context.trailer();

        // 1. Identifier resolution: Local, Upvalue, ModuleSlot, ComptimeConstant, or Direct Function Call
        if (atom?.identifier() != null && atom.DOT() == null)
        {
            string id = atom.identifier().GetText();
            bool isCall = trailers is { Length: > 0 } && trailers[0].LPAR() != null;

            if (isCall && (_knownFunctions.Contains(id) || _knownTypes.Contains(id)))
            {
                CurrentFrame.DemotedDirectCalls++;
                _report.TotalDemotedDirectCalls++;
            }
            else if (TryResolveLexicalCoordinate(id, out var coord))
            {
                _report.VariableCoordinates[atom] = coord;
                if (coord.Kind == PilotDemotedBindingKind.UpvalueSlot)
                {
                    CurrentFrame.DemotedUpvalues++;
                    _report.TotalDemotedUpvalues++;
                }
                else if (coord.Kind == PilotDemotedBindingKind.DynamicScopeFallback)
                {
                    CurrentFrame.RemainingDynamicLookups++;
                    _report.TotalRemainingDynamicLookups++;
                    if (CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime)
                    {
                        _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                            "COMPTIME002",
                            $"Dynamic variable lookup '{id}' is forbidden in '@zero_runtime' / '@hard_realtime' scope '{CurrentFrame.Name}'.",
                            context.Start.Line,
                            context.Start.Column,
                            isError: true));
                    }
                }
            }
        }

        // 2. Inspect trailers: Field slots, Method calls, Unit erasure, Call-quote projections
        if (trailers != null && trailers.Length > 0)
        {
            string? currentReceiverType = ResolveAtomStaticTypeName(atom);

            for (int i = 0; i < trailers.Length; i++)
            {
                var t = trailers[i];

                // Unit expression trailer `<m/s>` (19.1.4)
                if (t.unit_expr() != null)
                {
                    _report.ErasedUnitNodes.Add(t);
                    CurrentFrame.ErasedUnitsAndStates++;
                    _report.TotalErasedUnitsAndStates++;
                    continue;
                }

                // Call-quote projection `!!`, `!&`, `!@` (19.1.5)
                if (t.call_quote_op() != null)
                {
                    string opText = t.call_quote_op().GetText();
                    if (opText is "!!" or "!&" or "!@" or "!")
                    {
                        _report.PrecomputedCallQuoteNodes.Add(context);
                        CurrentFrame.PrecomputedCallQuotes++;
                        _report.TotalPrecomputedCallQuotes++;
                    }
                    continue;
                }

                // Member access `.field` or method call `.method(args)` (19.1.1 & 19.1.2)
                if (t.identifier() != null && (t.DOT() != null || t.SAFE_NAV() != null))
                {
                    string memberName = t.identifier().GetText();
                    bool isMethodCall = i + 1 < trailers.Length && trailers[i + 1].LPAR() != null;

                    if (isMethodCall)
                    {
                        if (currentReceiverType != null &&
                            string.Equals(currentReceiverType, "dynamic", StringComparison.OrdinalIgnoreCase) &&
                            (CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime))
                        {
                            _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                                "COMPTIME004",
                                $"Dynamic method dispatch '.{memberName}(...)' on 'dynamic' receiver is forbidden in '@zero_runtime' scope '{CurrentFrame.Name}'.",
                                t.Start.Line,
                                t.Start.Column,
                                isError: true));
                        }
                        else
                        {
                            CurrentFrame.DemotedDirectCalls++;
                            _report.TotalDemotedDirectCalls++;
                        }
                    }
                    else
                    {
                        string? cleanType = StripGenericsAndState(currentReceiverType);
                        if (!string.IsNullOrEmpty(cleanType) &&
                            _report.NominalFieldLayouts.TryGetValue(cleanType, out var fieldList))
                        {
                            int slotIdx = IndexOfOrdinal(fieldList, memberName);
                            if (slotIdx >= 0)
                            {
                                _report.FieldAccesses[t] = new PilotDemotedFieldAccess(
                                    cleanType, memberName, slotIdx, slotIdx * 8, t.Start.Line);
                                CurrentFrame.DemotedFieldSlots++;
                                _report.TotalDemotedFieldSlots++;
                            }
                        }
                        else if (currentReceiverType != null &&
                                 (string.Equals(currentReceiverType, "dynamic", StringComparison.OrdinalIgnoreCase) ||
                                  string.Equals(currentReceiverType, "any", StringComparison.OrdinalIgnoreCase)))
                        {
                            CurrentFrame.RemainingDynamicLookups++;
                            _report.TotalRemainingDynamicLookups++;
                            if (CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime)
                            {
                                _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                                    "COMPTIME002",
                                    $"Dynamic member lookup '.{memberName}' on '{currentReceiverType}' receiver is forbidden in '@zero_runtime' scope '{CurrentFrame.Name}'.",
                                    t.Start.Line,
                                    t.Start.Column,
                                    isError: true));
                            }
                        }
                    }
                }
            }
        }

        return base.VisitAtom_expr(context);
    }

    public override object? VisitInline_foreign_block(PilotParser.Inline_foreign_blockContext context)
    {
        CurrentFrame.RemainingAstFallbacks++;
        _report.TotalRemainingAstFallbacks++;
        if (CurrentFrame.IsZeroRuntime || CurrentFrame.IsHardRealtime)
        {
            _report.Diagnostics.Add(new PilotAnalysisDiagnostic(
                "COMPTIME001",
                $"Inline foreign polyglot block is forbidden inside '@zero_runtime' / '@hard_realtime' scope '{CurrentFrame.Name}'.",
                context.Start.Line,
                context.Start.Column,
                isError: true));
        }
        return null;
    }

    private bool TryResolveLexicalCoordinate(string name, out PilotDemotedVariableCoordinate coordinate)
    {
        if (_comptimeEvaluator.ConstValues.ContainsKey(name))
        {
            coordinate = new PilotDemotedVariableCoordinate(name, PilotDemotedBindingKind.ComptimeConstant, -1, 0);
            return true;
        }

        for (int i = _frames.Count - 1; i >= 0; i--)
        {
            var frame = _frames[i];
            if (frame.DynamicVars.Contains(name))
            {
                coordinate = new PilotDemotedVariableCoordinate(name, PilotDemotedBindingKind.DynamicScopeFallback, -1, 0);
                return true;
            }
            if (frame.ContextualParams.Contains(name))
            {
                int ctxSlot = PilotExecutionContext.InternContextSlotId(name);
                coordinate = new PilotDemotedVariableCoordinate(name, PilotDemotedBindingKind.ContextDisplaySlot, ctxSlot, 0);
                return true;
            }
            if (frame.Slots.TryGetValue(name, out int slot))
            {
                int depthDelta = (_frames.Count - 1) - i;
                if (depthDelta == 0)
                {
                    var kind = frame.IsModuleRoot ? PilotDemotedBindingKind.ModuleSlot : PilotDemotedBindingKind.LocalSlot;
                    coordinate = new PilotDemotedVariableCoordinate(name, kind, slot, 0);
                    return true;
                }
                coordinate = new PilotDemotedVariableCoordinate(name, PilotDemotedBindingKind.UpvalueSlot, slot, depthDelta);
                return true;
            }
        }

        coordinate = default!;
        return false;
    }

    private string? ResolveAtomStaticTypeName(PilotParser.AtomContext? atom)
    {
        if (atom?.identifier() == null || atom.DOT() != null) return null;
        string id = atom.identifier().GetText();
        for (int i = _frames.Count - 1; i >= 0; i--)
        {
            if (_frames[i].LocalTypes.TryGetValue(id, out string? localType))
            {
                return localType;
            }
        }
        if (_typeEngine.InferredTypes.TryGetValue(id, out var pt) && !string.IsNullOrEmpty(pt.Name))
        {
            return pt.Name;
        }
        return null;
    }

    private string? ResolveFactorStaticTypeName(PilotParser.FactorContext? factor)
    {
        var atomExpr = factor?.power()?.atom_expr();
        if (atomExpr == null) return null;
        if (atomExpr.trailer() == null || atomExpr.trailer().Length == 0)
        {
            return StripGenericsAndState(ResolveAtomStaticTypeName(atomExpr.atom()));
        }
        string? callee = atomExpr.atom()?.identifier()?.GetText();
        if (!string.IsNullOrEmpty(callee) && _knownTypes.Contains(callee))
        {
            return callee;
        }
        return null;
    }

    private bool TryInferConstructedTypeName(PilotParser.TestContext expr, out string? typeName)
    {
        typeName = null;
        string raw = expr.GetText().Trim();
        int parenIdx = raw.IndexOf('(');
        if (parenIdx > 0)
        {
            string prefix = StripGenericsAndState(raw[..parenIdx]) ?? "";
            if (_knownTypes.Contains(prefix))
            {
                typeName = prefix;
                return true;
            }
        }
        return false;
    }

    private static string? StripGenericsAndState(string? typeName)
    {
        if (string.IsNullOrEmpty(typeName)) return null;
        int idx = typeName.IndexOfAny(new[] { '[', '<', '?' });
        return idx > 0 ? typeName[..idx].Trim() : typeName.Trim();
    }

    private static int IndexOfOrdinal(IReadOnlyList<string> list, string target)
    {
        for (int i = 0; i < list.Count; i++)
        {
            if (string.Equals(list[i], target, StringComparison.Ordinal))
                return i;
        }
        return -1;
    }

    private static IEnumerable<string> ExtractPatternIdentifiers(PilotParser.Binding_patternContext? pat)
    {
        if (pat == null) yield break;
        if (pat.identifier() != null)
        {
            yield return pat.identifier().GetText();
            yield break;
        }
        if (pat.tuple_pattern()?.binding_pattern_item() is { } tupItems)
        {
            foreach (var item in tupItems)
                foreach (var sub in ExtractPatternIdentifiers(item.binding_pattern()))
                    yield return sub;
        }
        if (pat.list_pattern()?.binding_pattern_item() is { } listItems)
        {
            foreach (var item in listItems)
                foreach (var sub in ExtractPatternIdentifiers(item.binding_pattern()))
                    yield return sub;
        }
        if (pat.record_pattern()?.record_pattern_field() is { } recFields)
        {
            foreach (var f in recFields)
            {
                if (f.binding_pattern() != null)
                {
                    foreach (var sub in ExtractPatternIdentifiers(f.binding_pattern()))
                        yield return sub;
                }
                else if (f.identifier() != null)
                {
                    yield return f.identifier().GetText();
                }
            }
        }
    }

    private static bool HasZeroRuntimePragmaOrDecorator(PilotParser.ProgramContext program)
    {
        if (program?.stmt() == null) return false;
        foreach (var s in program.stmt())
        {
            var decs = s.compound_stmt()?.func_def()?.decorators()
                    ?? s.compound_stmt()?.struct_def()?.decorators()
                    ?? s.compound_stmt()?.class_def()?.decorators();
            if (decs != null)
            {
                GetDecoratorFlags(decs, out bool z, out _);
                if (z && s.compound_stmt()?.func_def() == null) return true;
            }
        }
        return false;
    }

    private static void GetDecoratorFlags(PilotParser.DecoratorsContext? decorators, out bool isZeroRuntime, out bool isHardRealtime)
    {
        isZeroRuntime = false;
        isHardRealtime = false;
        if (decorators?.decorator() == null) return;
        foreach (var d in decorators.decorator())
        {
            string name = d.dotted_name()?.GetText() ?? "";
            if (name is "zero_runtime" or "ZeroRuntime" or "no_runtime" or "comptime_only")
            {
                isZeroRuntime = true;
            }
            else if (name is "hard_realtime" or "HardRealtime" or "hard_rt" or "noalloc")
            {
                isHardRealtime = true;
            }
        }
    }

    private void FinalizeFrame(LexicalFrame frame)
    {
        var summary = new PilotFunctionAuditSummary(
            frame.Name,
            frame.IsZeroRuntime,
            frame.IsHardRealtime,
            frame.IsComptime,
            frame.DemotedLocals,
            frame.DemotedUpvalues,
            frame.DemotedFieldSlots,
            frame.DemotedDirectCalls,
            frame.DemotedProjections,
            frame.ErasedUnitsAndStates,
            frame.PrecomputedCallQuotes,
            frame.ElidedContracts,
            frame.DemotedContextSlots,
            frame.RemainingAstFallbacks,
            frame.RemainingDynamicLookups);
        _report.FunctionAudits.Add(summary);
        _report.FunctionSummaries[frame.Name] = summary;
    }
