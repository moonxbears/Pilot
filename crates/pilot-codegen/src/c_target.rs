//! Milestone 35.1: C11/C23 Code Generator.

use std::fmt::Write;

pub struct CTargetEmitter {
    out: String,
}

impl Default for CTargetEmitter {
    fn default() -> Self {
        Self::new()
    }
}

impl CTargetEmitter {
    pub fn new() -> Self {
        Self {
            out: String::with_capacity(1024),
        }
    }

    pub fn emit_header(&mut self) {
        writeln!(&mut self.out, "/* Generated by Pilot Compiler (C11/C23 Backend) */").unwrap();
        writeln!(&mut self.out, "#include <stdint.h>").unwrap();
        writeln!(&mut self.out, "#include <stdbool.h>").unwrap();
        writeln!(&mut self.out, "#include <stddef.h>").unwrap();
        writeln!(&mut self.out, "#include \"pilot_rt.h\"").unwrap();
        writeln!(&mut self.out).unwrap();
    }

    pub fn emit_function(&mut self, ret_type: &str, name: &str, params: &[(&str, &str)], body: &str) {
        let param_strs: Vec<String> = params.iter().map(|(ty, p)| format!("{} {}", ty, p)).collect();
        let param_list = if param_strs.is_empty() { "void".to_string() } else { param_strs.join(", ") };
        writeln!(&mut self.out, "{} {}({}) {{", ret_type, name, param_list).unwrap();
        writeln!(&mut self.out, "{}", body).unwrap();
        writeln!(&mut self.out, "}}").unwrap();
        writeln!(&mut self.out).unwrap();
    }

    pub fn finish(self) -> String {
        self.out
    }
}
